namespace Helix.Bindgen.Model;

/// <summary>A C++ type as written: a qualified name, template arguments, const, pointers and references.</summary>
public sealed class TypeRef
{
    public string Name = "";
    public List<TypeRef> Arguments = new();
    public bool Const;
    public int Pointers;
    public bool Reference;

    public string Spelling()
    {
        string s = (Const ? "const " : "") + Name;
        if (Arguments.Count > 0)
            s += "<" + string.Join(", ", Arguments.Select(a => a.Spelling())) + ">";
        s += new string('*', Pointers);
        if (Reference)
            s += "&";
        return s;
    }

    /// <summary>The type without const, pointers and references.</summary>
    public TypeRef Bare() => new() { Name = Name, Arguments = Arguments };

    public override string ToString() => Spelling();
}

/// <summary>The arguments of a tag: flags and named values.</summary>
public sealed class TagArgs
{
    public readonly HashSet<string> Flags = new();
    public readonly Dictionary<string, string> Values = new();

    public bool Has(string flag) => Flags.Contains(flag);
    public string? Get(string key) => Values.TryGetValue(key, out string? v) ? v : null;
}

public sealed class Location
{
    public string File = "";
    public int Line;
    public override string ToString() => $"{File}({Line})";
}

public enum TypeKind
{
    Class,
    Struct,
    Enum,
    Interface,
}

public sealed class FieldModel
{
    public string Name = "";
    public TypeRef Type = new();
    public bool Static;
    public TagArgs Tag = new();
    public Location Where = new();
    public string CsName => Tag.Get("Name") ?? Name;
}

public sealed class ParameterModel
{
    public string Name = "";
    public TypeRef Type = new();
    public string? Default;
}

public sealed class MethodModel
{
    public string Name = "";
    public TypeRef Return = new();
    public List<ParameterModel> Parameters = new();
    public bool Static;
    public bool Virtual;
    public bool Const;
    /// <summary>Pure virtual (= 0).</summary>
    public bool Abstract;
    public bool Public = true;
    /// <summary>A C++ constructor (tagged HX_FUNCTION(Constructor)), not a static factory.</summary>
    public bool RealConstructor;
    public TagArgs Tag = new();
    public Location Where = new();
    public string CsName => Tag.Get("Name") ?? Name;
    /// <summary>Its name in the C++ script API (the tag ApiName: when C# written by hand has the C# name).</summary>
    public string ApiName => Tag.Get("ApiName") ?? CsName;
    public bool Leaf => Tag.Has("Leaf");
}

public sealed class PropertyModel
{
    public string CsName = "";
    /// <summary>Its name in the C++ script API (the getter's tag ApiName: when C# written by hand has the C# name).</summary>
    public string ApiName => Getter.Tag.Get("ApiName") ?? CsName;
    public MethodModel Getter = new();
    public MethodModel? Setter;
    public bool Static => Getter.Static;
}

public sealed class EventModel
{
    public string CsName = "";
    /// <summary>Its name in the C++ script API (the tag ApiName: when its C# name is taken by C# written by hand).</summary>
    public string ApiName = "";
    /// <summary>The C++ member: a field or a function returning a reference to the event.</summary>
    public string Member = "";
    public bool IsFunction;
    public bool Static;
    /// <summary>Event (handlers return nothing) or Query (handlers answer bool).</summary>
    public bool Query;
    public List<TypeRef> Arguments = new();
    public TagArgs Tag = new();
    public Location Where = new();
}

public sealed class EnumValueModel
{
    public string Name = "";
    public long Value;
}

public sealed class TypeModel
{
    public TypeKind Kind;
    public string Name = "";
    /// <summary>The C++ namespace path (a::b) and the C# namespace.</summary>
    public string CppNamespace = "";
    public string CsNamespace = "";
    public List<string> Bases = new();
    public TagArgs Tag = new();
    public Location Where = new();
    public List<FieldModel> Fields = new();
    public List<MethodModel> Methods = new();
    public List<PropertyModel> Properties = new();
    public List<EventModel> Events = new();
    public List<EnumValueModel> EnumValues = new();
    /// <summary>The functions without a tag (any access): property setters and the methods of script classes.</summary>
    public List<MethodModel> Untagged = new();
    public TypeRef? Underlying;
    /// <summary>Set when the type is nested in another tagged type.</summary>
    public TypeModel? Outer;
    /// <summary>A type of a referenced module: known to the mapping, generated by its own module.</summary>
    public bool External;

    public string CppName => (CppNamespace.Length > 0 ? CppNamespace + "::" : "") + (Outer != null ? Outer.Name + "::" : "") + Name;
    public string CsFullName => Outer != null ? Outer.CsFullName + "." + Name : (CsNamespace.Length > 0 ? CsNamespace + "." : "") + Name;
    /// <summary>The name in the registry: nested types as Outer.Inner in the namespace.</summary>
    public string RegistryName => Outer != null ? Outer.RegistryName + "." + Name : Name;
    /// <summary>A name usable in C identifiers.</summary>
    public string Ident => CsFullName.Replace('.', '_');
}

public sealed class ModuleModel
{
    public string Name = "";
    public List<TypeModel> Types = new();
    public List<string> Headers = new();
    /// <summary>C++ classes bound by hand to C# classes (HX_HANDLE): their C++ names to their C# types. Their objects
    /// cross as the u64 of their Id(); a field of one is a C# property answering the C# object of that id.</summary>
    public Dictionary<string, string> Handles = new();
    /// <summary>Structs only files hold (HX_STRUCT(SerializedOnly)): not bound; fields of them are serialized through
    /// their member Transfer and left out of C#. Their C++ names (bare and qualified).</summary>
    public Dictionary<string, string> SerializedOnly = new();
}

/// <summary>An error with its place.</summary>
public sealed class BindgenException(Location where, string message) : Exception($"{where}: error: {message}")
{
    public Location Where { get; } = where;
}
