using System.Globalization;
using Helix.Bindgen.Model;

namespace Helix.Bindgen.Generators;

/// <summary>
/// The C# side of a module: structs of the same layout, enums, partial classes whose members call the native thunks
/// through function pointers, events over GC handles, and the loader that fills the function pointers from the native
/// module, checks its shape and registers the types and wrapper factories.
/// </summary>
public sealed class CsGenerator
{
    static readonly HashSet<string> Keywords = new()
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
        "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
    };

    readonly Binding _b;
    readonly Code _c = new();
    readonly Dictionary<EventModel, int> _events = new();

    CsGenerator(Binding binding) => _b = binding;

    public static string Generate(Binding binding)
    {
        var g = new CsGenerator(binding);
        g.Write();
        return g._c.ToString();
    }

    string ModuleIdent => _b.Ident(_b.Module.Name);
    string ModuleClass => $"global::Helix.Interop.Generated.HxModule_{ModuleIdent}";

    static string Id(string name) => Keywords.Contains(name) ? "@" + name : name;
    static string G(TypeModel t) => "global::" + t.CsFullName;

    // ------------------------------------------------------------------------------------------- C# spellings

    string CsType(Mapping m) => m.Kind switch
    {
        MapKind.Void => "void",
        MapKind.Bool => "bool",
        MapKind.Primitive => m.Cs,
        MapKind.String => "string",
        MapKind.TypeId => "global::System.Type",
        MapKind.Array => CsType(m.Element!) + "[]",
        _ => G(m.Bound!),
    };

    // The C# type of the value a native field of the mapping holds in memory (struct fields, arrays' items).
    string CsValue(Mapping m) => m.Kind == MapKind.Bool ? "bool" : CsType(m);

    // The type of one native value of the function pointer for an `in` argument.
    string OutAbi(Mapping m) => m.Kind switch
    {
        MapKind.Bool => "byte*",
        MapKind.TypeId => "uint*",
        MapKind.String => "global::Helix.Interop.InteropString*",
        MapKind.Object => "global::Helix.Interop.InteropObject*",
        MapKind.Array => "global::Helix.Interop.InteropArray*",
        _ => CsType(m) + "*",
    };

    string Root(Mapping m) => G(_b.RootOf(m.Bound!));

    // ------------------------------------------------------------------------------------------- the file

    void Write()
    {
        _c.Line("// Generated by Helix.Bindgen. Do not edit.");
        _c.Line("#nullable disable");
        _c.Line("#pragma warning disable CS0108, CS0114, CS0169, CS0649, CS1591");
        _c.Line();
        foreach (IGrouping<string, TypeModel> ns in _b.Module.Types.Where(t => !t.External && t.Outer == null).GroupBy(t => t.CsNamespace))
        {
            bool named = ns.Key.Length > 0;
            if (named)
                _c.Open($"namespace {ns.Key}");
            foreach (TypeModel t in ns)
                WriteType(t);
            if (named)
                _c.Close();
            _c.Line();
        }
        WriteModule();
    }

    IEnumerable<TypeModel> Nested(TypeModel t) => _b.Module.Types.Where(n => n.Outer == t && !n.External);

    void Attributes(TagArgs tag)
    {
        string? a = tag.Get("Attributes");
        if (a != null)
            _c.Line(a);
    }

    void WriteType(TypeModel t)
    {
        Attributes(t.Tag);
        switch (t.Kind)
        {
            case TypeKind.Enum:
                _c.Open($"public enum {t.Name} : {_b.Map.EnumCs(t)}");
                foreach (EnumValueModel v in t.EnumValues)
                    _c.Line($"{v.Name} = {(v.Value < 0 ? "unchecked((" + _b.Map.EnumCs(t) + ")(" + v.Value + "))" : v.Value.ToString(CultureInfo.InvariantCulture))},");
                _c.Close();
                return;
            case TypeKind.Struct:
                _c.Line("[global::System.Runtime.InteropServices.StructLayout(global::System.Runtime.InteropServices.LayoutKind.Sequential)]");
                _c.Open($"{(t.Tag.Has("Internal") ? "internal" : "public")} partial struct {t.Name}");
                foreach (FieldModel f in t.Fields)
                {
                    Attributes(f.Tag);
                    _c.Line($"{(f.Tag.Has("Private") ? "private" : "public")} {CsValue(_b.Map.Map(f.Type, f.Where, f.Name))} {Id(f.CsName)};");
                }
                foreach (TypeModel n in Nested(t))
                    WriteType(n);
                _c.Close();
                return;
            case TypeKind.Interface:
                _c.Open($"public partial interface {t.Name}{Inherits(t)}");
                foreach (PropertyModel p in t.Properties)
                    _c.Line($"{CsType(_b.Map.Map(p.Getter.Return, p.Getter.Where, p.CsName))} {Id(p.CsName)} {{ get;{(p.Setter != null ? " set;" : "")} }}");
                foreach (MethodModel m in t.Methods)
                    _c.Line($"{CsType(_b.Map.Map(m.Return, m.Where, m.Name))} {Id(m.CsName)}({string.Join(", ", m.Parameters.Select(p => ParamDecl(m, p)))});");
                _c.Close();
                return;
        }
        string mods = t.Tag.Has("Static") ? "static " : t.Tag.Has("Sealed") ? "sealed " : t.Tag.Has("Abstract") ? "abstract " : "";
        _c.Open($"{(t.Tag.Has("Internal") ? "internal" : "public")} {mods}unsafe partial class {t.Name}{Inherits(t)}");
        bool objectClass = _b.IsObjectClass(t);
        if (objectClass)
        {
            bool isRoot = _b.RootOf(t) == t;
            if (isRoot)
            {
                _c.Line("internal ulong m_HxId;");
                _c.Line("// An object of a C# class deriving from a generated one: base calls reach the C++ implementation.");
                _c.Line("internal bool m_HxDerived;");
                _c.Line("internal " + t.Name + "(global::Helix.Interop.ObjectId id) { m_HxId = id.Value; }");
                WriteRootEquality(t);
            }
            else
                _c.Line("internal " + t.Name + "(global::Helix.Interop.ObjectId id) : base(id) { }");
            bool zeroArgCtor = t.Methods.Any(m => m.Tag.Has("Constructor") && m.Parameters.Count == 0 && !m.Tag.Has("Hidden"));
            if (!zeroArgCtor)
                _c.Line($"{(t.Tag.Has("Sealed") ? "private" : "protected")} {t.Name}() {{ }}");
        }
        foreach (Thunk th in _b.Thunks.Where(x => x.Owner == t))
            WriteMember(t, th);
        WriteInheritedOverrides(t);
        // The constructors of a class abstract in C++: only C# subclasses are made.
        if (_b.IsAbstractCpp(t))
            foreach (MethodModel m in t.Methods.Where(m => m.RealConstructor && !m.Tag.Has("Hidden")))
                WriteConstructor(t, null, m, string.Join(", ", m.Parameters.Select(p => ParamDecl(m, p))), $"{t.Name}.{t.Name}");
        foreach (TypeModel n in Nested(t))
            WriteType(n);
        _c.Close();
    }

    // The reference's Object semantics: a destroyed object compares equal to null, two live ones by their native
    // object; `is null` sees only the C# reference.
    void WriteRootEquality(TypeModel t)
    {
        Thunk alive = _b.Thunks.First(x => x.Owner == t && x.Kind == ThunkKind.Alive);
        _fnTypes[alive] = "delegate* unmanaged[Cdecl, SuppressGCTransition]<ulong, byte*, int>";
        Thunk get = _b.Thunks.First(x => x.Owner == t && x.Kind == ThunkKind.GetWrapper);
        _fnTypes[get] = "delegate* unmanaged[Cdecl]<ulong, ulong*, int>";
        Thunk set = _b.Thunks.First(x => x.Owner == t && x.Kind == ThunkKind.SetWrapper);
        _fnTypes[set] = "delegate* unmanaged[Cdecl]<ulong, ulong, int>";
        string n = t.Name;
        _c.Line();
        _c.Open("internal static bool HxAlive(ulong id)");
        _c.Line("if (id == 0)");
        _c.Line("    return false;");
        _c.Line("byte alive;");
        _c.Line($"return {ModuleClass}.{alive.Name}(id, &alive) == 0 && alive != 0;");
        _c.Close();
        _c.Open($"static bool HxCompare({n} x, {n} y)");
        _c.Line("bool xNull = x is null, yNull = y is null;");
        _c.Line("if (xNull && yNull)");
        _c.Line("    return true;");
        _c.Line("if (yNull)");
        _c.Line("    return !HxAlive(x.m_HxId);");
        _c.Line("if (xNull)");
        _c.Line("    return !HxAlive(y.m_HxId);");
        _c.Line("return x.m_HxId == y.m_HxId;");
        _c.Close();
        _c.Line($"public static bool operator ==({n} x, {n} y) => HxCompare(x, y);");
        _c.Line($"public static bool operator !=({n} x, {n} y) => !HxCompare(x, y);");
        _c.Line($"public static implicit operator bool({n} exists) => !HxCompare(exists, null);");
        _c.Open("public override bool Equals(object other)");
        _c.Line($"if (other is not null && other is not {n})");
        _c.Line("    return false;");
        _c.Line($"return HxCompare(this, ({n})other);");
        _c.Close();
        _c.Line("public override int GetHashCode() => m_HxId.GetHashCode();");
    }

    string Inherits(TypeModel t)
    {
        var list = new List<string>();
        TypeModel? b = _b.BaseOf(t);
        if (b != null)
            list.Add(G(b));
        list.AddRange(_b.InterfacesOf(t).Select(G));
        return list.Count == 0 ? "" : " : " + string.Join(", ", list);
    }

    string Self(Thunk th) => th.Static ? "" : "m_HxId";

    // ------------------------------------------------------------------------------------------- calls

    sealed class Call
    {
        public readonly List<string> Abi = new();
        public readonly List<string> Args = new();
        public readonly List<string> Pre = new();
        public readonly List<string> Fixed = new();
        public readonly List<string> Post = new();
        // Right after the call, before its status is looked at (GC handles made for the call).
        public readonly List<string> Cleanup = new();
    }

    bool IsOut(MethodModel m, ParameterModel p) =>
        (m.Tag.Get("Out") ?? "").Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).Contains(p.Name);

    string ParamDecl(MethodModel m, ParameterModel p, string? overrideType = null)
    {
        Mapping pm = _b.Map.Map(p.Type, m.Where, p.Name);
        string mod = pm.ByRef ? (IsOut(m, p) ? "out " : "ref ") : "";
        string def = p.Default != null && !pm.ByRef ? " = " + Default(p.Default, pm, m.Where) : "";
        return $"{mod}{overrideType ?? CsType(pm)} {Id(p.Name)}{def}";
    }

    string Default(string cpp, Mapping m, Location where)
    {
        string v = cpp.Trim();
        if (v == "nullptr" || v == "NULL")
            return "null";
        if (v is "true" or "false")
            return v;
        if (v.StartsWith('"'))
            return v;
        if (v == "{}" || v.EndsWith("{}", StringComparison.Ordinal) || v.EndsWith("()", StringComparison.Ordinal))
            return "default";
        if (m.Kind == MapKind.Enum && v.Contains("::"))
            return G(m.Bound!) + "." + v.Split("::")[^1];
        if (v.Length > 0 && (char.IsDigit(v[0]) || v[0] == '-' || v[0] == '.'))
        {
            string n = v.TrimEnd('f', 'F', 'u', 'U', 'l', 'L');
            if (v.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
                n = v.TrimEnd('u', 'U', 'l', 'L');
            return m.Cs switch
            {
                "float" => n + "f",
                "double" => n.Contains('.') || n.Contains('e') ? n : n + ".0",
                _ => n,
            };
        }
        throw new BindgenException(where, $"the default value {cpp} has no C# spelling Bindgen knows");
    }

    // A C# value going to the thunk.
    void In(Call call, Mapping m, string n, string local, bool isOut)
    {
        if (m.ByRef)
        {
            switch (m.Kind)
            {
                case MapKind.Object:
                    call.Pre.Add($"global::Helix.Interop.InteropObject {local};");
                    call.Abi.Add("global::Helix.Interop.InteropObject*");
                    call.Args.Add($"&{local}");
                    call.Post.Add($"{n} = global::Helix.Interop.Objects.Wrap<{CsType(m)}>({local});");
                    return;
                default:
                    if (isOut)
                        call.Pre.Add($"{n} = default;");
                    call.Fixed.Add($"fixed ({CsValue(m)}* {local} = &{n})");
                    call.Abi.Add($"{CsValue(m)}*");
                    call.Args.Add(local);
                    return;
            }
        }
        switch (m.Kind)
        {
            case MapKind.Primitive:
            case MapKind.Enum:
                call.Abi.Add(CsType(m));
                call.Args.Add(n);
                break;
            case MapKind.Bool:
                call.Abi.Add("byte");
                call.Args.Add($"(byte)({n} ? 1 : 0)");
                break;
            case MapKind.TypeId:
                call.Abi.Add("uint");
                call.Args.Add($"global::Helix.Interop.Types.Of({n})");
                break;
            case MapKind.Struct:
                call.Abi.Add(CsType(m) + "*");
                call.Args.Add($"&{n}");
                break;
            case MapKind.String:
                call.Fixed.Add($"fixed (char* {local} = {n})");
                call.Abi.Add("char*");
                call.Abi.Add("int");
                call.Args.Add(local);
                call.Args.Add($"{n} is null ? 0 : {n}.Length");
                break;
            case MapKind.Object:
                call.Abi.Add("ulong");
                call.Args.Add($"{n} is null ? 0ul : (({Root(m)}){n}).m_HxId");
                break;
            case MapKind.Interface:
                // A native wrapper crosses as its object; any other C# object as a GC handle for the call.
                call.Pre.Add($"global::Helix.Interop.InteropObject {local}_o = global::Helix.Interop.Objects.Pass({n});");
                call.Pre.Add($"var {local}_g = {n} is not null && {local}_o.id == 0 ? global::System.Runtime.InteropServices.GCHandle.Alloc({n}) : default;");
                call.Abi.Add("ulong");
                call.Abi.Add("uint");
                call.Abi.Add("ulong");
                call.Args.Add($"{local}_o.id");
                call.Args.Add($"{local}_o.type");
                call.Args.Add($"{local}_g.IsAllocated ? (ulong)global::System.Runtime.InteropServices.GCHandle.ToIntPtr({local}_g) : 0ul");
                call.Cleanup.Add($"if ({local}_g.IsAllocated)");
                call.Cleanup.Add($"    {local}_g.Free();");
                break;
            case MapKind.Array:
            {
                Mapping e = m.Element!;
                if (e.Kind == MapKind.String)
                {
                    call.Pre.Add($"global::Helix.Interop.InteropString16* {local} = global::Helix.Interop.Native.PassStrings({n});");
                    call.Abi.Add("global::Helix.Interop.InteropString16*");
                }
                else if (e.Kind == MapKind.Object)
                {
                    call.Pre.Add($"ulong[] {local}_ids = global::Helix.Interop.Objects.Ids({n}, x => (({Root(e)})x).m_HxId);");
                    call.Fixed.Add($"fixed (ulong* {local} = {local}_ids)");
                    call.Abi.Add("ulong*");
                }
                else
                {
                    call.Fixed.Add($"fixed ({CsValue(e)}* {local} = {n})");
                    call.Abi.Add($"{CsValue(e)}*");
                }
                call.Abi.Add("int");
                call.Args.Add(local);
                call.Args.Add($"{n} == null ? 0 : {n}.Length");
                break;
            }
            default:
                throw new InvalidOperationException(m.Kind.ToString());
        }
    }

    // The result local, and the expression that turns it into the C# value.
    (string Decl, string Value) Result(Mapping m) => m.Kind switch
    {
        MapKind.Bool => ("byte hx_r;", "hx_r != 0"),
        MapKind.TypeId => ("uint hx_r;", "global::Helix.Interop.Types.FromNative(hx_r)"),
        MapKind.String => ("global::Helix.Interop.InteropString hx_r;", "global::Helix.Interop.Native.ReadString(hx_r)"),
        MapKind.Object => ("global::Helix.Interop.InteropObject hx_r;", $"global::Helix.Interop.Objects.Wrap<{CsType(m)}>(hx_r)"),
        MapKind.Array => m.Element!.Kind == MapKind.Object
            ? ("global::Helix.Interop.InteropArray hx_r;", $"global::Helix.Interop.Objects.WrapArray<{CsType(m.Element!)}>(hx_r)")
            : m.Element!.Kind == MapKind.String
                ? ("global::Helix.Interop.InteropArray hx_r;", "global::Helix.Interop.Native.ReadStrings(hx_r)")
                : ("global::Helix.Interop.InteropArray hx_r;", $"global::Helix.Interop.Native.ReadArray<{CsValue(m.Element!)}>(hx_r)"),
        _ => ($"{CsType(m)} hx_r;", "hx_r"),
    };

    string FnType(Thunk th, Call call, bool hasResult, Mapping result)
    {
        var abi = new List<string>();
        if (!th.Static)
            abi.Add("ulong");
        abi.AddRange(call.Abi);
        if (hasResult)
            abi.Add(OutAbi(result));
        abi.Add("int");
        return $"delegate* unmanaged[Cdecl{(th.Leaf ? ", SuppressGCTransition" : "")}]<{string.Join(", ", abi)}>";
    }

    readonly Dictionary<Thunk, string> _fnTypes = new();

    // The body of a member: the call through the function pointer, the status check, the result.
    void Body(Thunk th, Call call, Mapping result, string what, bool returns)
    {
        bool hasResult = result.Kind != MapKind.Void;
        _fnTypes[th] = FnType(th, call, hasResult, result);
        foreach (string l in call.Pre)
            _c.Line(l);
        (string decl, string value) = hasResult ? Result(result) : ("", "");
        if (hasResult)
            _c.Line(decl);
        var args = new List<string>();
        if (!th.Static)
            args.Add(Self(th));
        args.AddRange(call.Args);
        if (hasResult)
            args.Add("&hx_r");
        foreach (string f in call.Fixed)
            _c.Line(f);
        _c.Open();
        _c.Line($"int hx_s = {ModuleClass}.{th.Name}({string.Join(", ", args)});");
        foreach (string l in call.Cleanup)
            _c.Line(l);
        _c.Line("if (hx_s != 0)");
        _c.Line($"    global::Helix.Interop.Native.Fail(hx_s, \"{what}\");");
        _c.Close();
        foreach (string l in call.Post)
            _c.Line(l);
        if (returns && hasResult)
            _c.Line($"return {value};");
    }

    // ------------------------------------------------------------------------------------------- members

    void WriteMember(TypeModel t, Thunk th)
    {
        string st = th.Static ? "static " : "";
        switch (th.Kind)
        {
            case ThunkKind.FieldGet:
            {
                FieldModel f = th.Field!;
                Thunk? set = _b.Thunks.FirstOrDefault(x => x.Kind == ThunkKind.FieldSet && x.Field == f);
                Attributes(f.Tag);
                _c.Open($"{Access(f.Tag)} {st}{CsType(th.Type)} {Id(f.CsName)}");
                _c.Open("get");
                Body(th, new Call(), th.Type, $"{t.Name}.{f.CsName}", true);
                _c.Close();
                if (set != null)
                {
                    _c.Open("set");
                    var call = new Call();
                    In(call, Plain(th.Type), "value", "hx_v", false);
                    Body(set, call, new Mapping { Kind = MapKind.Void }, $"{t.Name}.{f.CsName}", false);
                    _c.Close();
                }
                _c.Close();
                return;
            }
            case ThunkKind.FieldSet:
                return;
            case ThunkKind.Method when th.Property != null:
            {
                if (th.IsSetter)
                    return;
                PropertyModel p = th.Property;
                Thunk? set = _b.Thunks.FirstOrDefault(x => x.Property == p && x.IsSetter);
                Attributes(p.Getter.Tag);
                _c.Open($"{Access(p.Getter.Tag)} {st}{CsType(th.Type)} {Id(p.CsName)}");
                _c.Open("get");
                Body(th, new Call(), th.Type, $"{t.Name}.{p.CsName}", true);
                _c.Close();
                if (set != null)
                {
                    _c.Open("set");
                    var call = new Call();
                    In(call, _b.Map.Map(p.Setter!.Parameters[0].Type, p.Setter.Where, p.CsName), "value", "hx_v", false);
                    Body(set, call, set.Type, $"{t.Name}.{p.CsName}", false);
                    _c.Close();
                }
                else if (p.Getter.Tag.Has("SetterThrows"))
                    // The member has a setter that is not supported (the C++ script API has the getter only).
                    _c.Line("set => throw new global::System.NotImplementedException();");
                _c.Close();
                return;
            }
            case ThunkKind.Method:
                WriteMethod(t, th);
                return;
            case ThunkKind.EventAdd:
                WriteEvent(t, th);
                return;
            case ThunkKind.EventRemove:
            case ThunkKind.GetWrapper:
            case ThunkKind.SetWrapper:
            case ThunkKind.Alive:
            case ThunkKind.NewDerived:
            case ThunkKind.BaseCall:
                return;
        }
    }

    static Mapping Plain(Mapping m) => new() { Kind = m.Kind, Cs = m.Cs, CppBare = m.CppBare, Size = m.Size, Align = m.Align, Element = m.Element, Bound = m.Bound };

    void WriteMethod(TypeModel t, Thunk th)
    {
        MethodModel m = th.Method!;
        Attributes(m.Tag);
        string what = $"{t.Name}.{m.CsName}";
        var call = new Call();
        for (int i = 0; i < m.Parameters.Count; i++)
        {
            ParameterModel p = m.Parameters[i];
            In(call, _b.Map.Map(p.Type, m.Where, p.Name), Id(p.Name), $"hx_p{i}", IsOut(m, p));
        }
        string ps = string.Join(", ", m.Parameters.Select(p => ParamDecl(m, p)));
        if (m.Tag.Has("Constructor"))
        {
            if (th.Type.Kind != MapKind.Object || th.Type.Bound != t)
                throw new BindgenException(m.Where, $"{what}: a Constructor returns a {t.Name}*");
            WriteConstructor(t, th, m, ps, what);
            return;
        }
        string st = th.Static ? "static " : "";
        if (m.Virtual && !th.Static)
        {
            bool first = _b.IsFirstDeclaration(t, m);
            _c.Open($"public {(first ? "virtual" : "override")} {CsType(th.Type)} {Id(m.CsName)}({ps})");
            if (_b.Overridables.ContainsKey(t))
            {
                // An object of a C# class deriving from this one: base calls reach the C++ implementation.
                Thunk baseCall = _b.Thunks.First(x => x.Owner == t && x.Kind == ThunkKind.BaseCall && Binding.Key(x.Method!) == Binding.Key(m));
                _c.Open("if (m_HxDerived)");
                Body(baseCall, NewCall(m), th.Type, what, true);
                _c.Close();
                _c.Open("else");
                Body(th, call, th.Type, what, true);
                _c.Close();
            }
            else
                Body(th, call, th.Type, what, true);
            _c.Close();
        }
        else
        {
            _c.Open($"{Access(m.Tag)} {st}{CsType(th.Type)} {Id(m.CsName)}({ps})");
            Body(th, call, th.Type, what, true);
            _c.Close();
        }
        if (m.Tag.Has("Lists") && th.Type.Kind == MapKind.Array)
        {
            // One overload per count of the defaulted parameters given (the list comes last, so no defaults).
            string list = $"global::System.Collections.Generic.List<{CsType(th.Type.Element!)}>";
            int required = m.Parameters.Count(p => p.Default == null);
            for (int k = required; k <= m.Parameters.Count; k++)
            {
                List<ParameterModel> given = m.Parameters.Take(k).ToList();
                string args = string.Join(", ", given.Select(p => Pass(m, p)));
                _c.Open($"public {st}void {Id(m.CsName)}({string.Join(", ", given.Select(p => NoDefault(ParamDecl(m, p))).Append($"{list} results"))})");
                _c.Line("if (results == null)");
                _c.Line("    throw new global::System.ArgumentNullException(nameof(results));");
                _c.Line("results.Clear();");
                _c.Line($"results.AddRange({Id(m.CsName)}({args}));");
                _c.Close();
            }
        }
        string? generic = m.Tag.Get("Generic");
        if (generic != null)
            WriteGeneric(m, th, generic, st);
    }

    Call NewCall(MethodModel m)
    {
        var call = new Call();
        for (int i = 0; i < m.Parameters.Count; i++)
        {
            ParameterModel p = m.Parameters[i];
            In(call, _b.Map.Map(p.Type, m.Where, p.Name), Id(p.Name), $"hx_b{i}", IsOut(m, p));
        }
        return call;
    }

    // A constructor: of the generated class itself (the native object made by the C++ constructor or factory, its
    // wrapper attached), or of a C# class deriving from it (the C++ subclass made with the C# object's strong handle
    // and the mask of the virtual functions the C# class overrides).
    void WriteConstructor(TypeModel t, Thunk? th, MethodModel m, string ps, string what)
    {
        string g = G(t);
        _c.Open($"public {t.Name}({ps})");
        _c.Open($"if (GetType() == typeof({g}))");
        if (m.RealConstructor && _b.IsAbstractCpp(t))
            _c.Line($"throw new global::System.InvalidOperationException(\"{t.Name} is abstract in C++: derive a C# class from it\");");
        else
        {
            Body(th!, NewCall(m), th!.Type, what, false);
            _c.Line("m_HxId = hx_r.id;");
            _c.Line($"global::Helix.Interop.Objects.Attach(this, hx_r.id, typeof({g}));");
            _c.Line("return;");
        }
        _c.Close();
        Thunk? derived = _b.Thunks.FirstOrDefault(x => x.Owner == t && x.Kind == ThunkKind.NewDerived && x.Method == m);
        if (derived == null)
        {
            _c.Line($"throw new global::System.NotSupportedException(\"{t.Name} has no C++ constructor a C# class can derive through\");");
            _c.Close();
            return;
        }
        Call call = NewCall(m);
        call.Abi.Add("ulong");
        call.Abi.Add("ulong");
        call.Pre.Add("var hx_self = global::System.Runtime.InteropServices.GCHandle.Alloc(this);");
        call.Args.Add("(ulong)global::System.Runtime.InteropServices.GCHandle.ToIntPtr(hx_self)");
        call.Args.Add($"{ModuleClass}.HxMask_{t.Ident}(GetType())");
        call.Cleanup.Add("if (hx_s != 0)");
        call.Cleanup.Add("    hx_self.Free();");
        _c.Open();
        Body(derived, call, derived.Type, what, false);
        _c.Line("m_HxId = hx_r.id;");
        _c.Line("m_HxDerived = true;");
        _c.Line("global::Helix.Interop.Objects.Remember(this, hx_r.id);");
        _c.Close();
        _c.Close();
    }

    // The virtual functions a derivable class inherits without declaring them: overrides that send the base calls
    // of C# subclasses to the C++ implementation.
    void WriteInheritedOverrides(TypeModel t)
    {
        if (!_b.Overridables.TryGetValue(t, out List<Overridable>? virtuals))
            return;
        foreach (Overridable o in virtuals.Where(o => o.NearestOwner != t))
        {
            MethodModel m = o.Nearest;
            Thunk baseCall = _b.Thunks.First(x => x.Owner == t && x.Kind == ThunkKind.BaseCall && x.Virtual == o);
            Mapping r = baseCall.Type;
            string ps = string.Join(", ", m.Parameters.Select(p => ParamDecl(m, p)));
            _c.Open($"public override {CsType(r)} {Id(m.CsName)}({ps})");
            _c.Open("if (m_HxDerived)");
            Body(baseCall, NewCall(m), r, $"{t.Name}.{m.CsName}", true);
            _c.Close();
            _c.Open("else");
            string args = string.Join(", ", m.Parameters.Select(p => Pass(m, p)));
            _c.Line(r.Kind == MapKind.Void ? $"base.{Id(m.CsName)}({args});" : $"return base.{Id(m.CsName)}({args});");
            _c.Close();
            _c.Close();
        }
    }

    static string NoDefault(string decl) => decl.Split(" = ", 2)[0];

    // A member tagged Internal is internal in C# (for C# written by hand in the assembly, still in the C++ API).
    static string Access(TagArgs tag) => tag.Has("Internal") ? "internal" : "public";

    string Pass(MethodModel m, ParameterModel p)
    {
        Mapping pm = _b.Map.Map(p.Type, m.Where, p.Name);
        return (pm.ByRef ? (IsOut(m, p) ? "out " : "ref ") : "") + Id(p.Name);
    }

    // The generic form: T for the TypeId argument (typeof(T)), for parameters, results and out arguments of the
    // constraint's type, with the casts to and from it.
    void WriteGeneric(MethodModel m, Thunk th, string generic, string st)
    {
        string[] parts = generic.Split(':', 2, StringSplitOptions.TrimEntries);
        string tp = parts[0];
        string? constraint = parts.Length > 1 ? parts[1] : null;
        TypeModel? bound = constraint != null ? _b.Map.Find(constraint.Replace(".", "::")) : null;
        bool IsT(Mapping pm) => bound != null && pm.Kind == MapKind.Object && pm.Bound == bound;
        var decls = new List<string>();
        var args = new List<string>();
        var pre = new List<string>();
        var post = new List<string>();
        foreach (ParameterModel p in m.Parameters)
        {
            Mapping pm = _b.Map.Map(p.Type, m.Where, p.Name);
            if (pm.Kind == MapKind.TypeId)
            {
                args.Add($"typeof({tp})");
                continue;
            }
            if (IsT(pm) && pm.ByRef)
            {
                decls.Add(ParamDecl(m, p, tp));
                pre.Add($"{CsType(pm)} hx_{p.Name} = default;");
                args.Add($"{(IsOut(m, p) ? "out" : "ref")} hx_{p.Name}");
                post.Add($"{Id(p.Name)} = ({tp})(object)hx_{p.Name};");
                continue;
            }
            decls.Add(ParamDecl(m, p, IsT(pm) ? tp : null));
            args.Add(Pass(m, p));
        }
        string call = $"{Id(m.CsName)}({string.Join(", ", args)})";
        Mapping r = th.Type;
        string ret;
        string value;
        if (IsT(r))
        {
            ret = tp;
            value = $"({tp})(object){call}";
        }
        else if (r.Kind == MapKind.Array && IsT(r.Element!))
        {
            ret = tp + "[]";
            value = $"global::System.Array.ConvertAll({call}, x => ({tp})(object)x)";
        }
        else
        {
            ret = CsType(r);
            value = call;
        }
        string where = constraint != null ? $" where {tp} : {constraint}" : "";
        _c.Open($"public {st}{ret} {Id(m.CsName)}<{tp}>({string.Join(", ", decls)}){where}");
        foreach (string l in pre)
            _c.Line(l);
        if (r.Kind == MapKind.Void)
            _c.Line(value + ";");
        else if (post.Count == 0)
            _c.Line($"return {value};");
        else
        {
            _c.Line($"var hx_g = {value};");
            foreach (string l in post)
                _c.Line(l);
            _c.Line("return hx_g;");
        }
        _c.Close();
        if (m.Tag.Has("Lists") && r.Kind == MapKind.Array && IsT(r.Element!))
        {
            // One overload per count of the defaulted parameters given (as the non-generic lists).
            var gen = m.Parameters.Where(p => _b.Map.Map(p.Type, m.Where, p.Name).Kind != MapKind.TypeId).ToList();
            int required = gen.Count(p => p.Default == null);
            for (int k = required; k <= gen.Count; k++)
            {
                var given = gen.Take(k).ToList();
                var callArgs = new List<string>();
                foreach (ParameterModel p in m.Parameters)
                {
                    if (_b.Map.Map(p.Type, m.Where, p.Name).Kind == MapKind.TypeId)
                        callArgs.Add($"typeof({tp})");
                    else if (given.Contains(p))
                        callArgs.Add(Pass(m, p));
                }
                string listCall = $"{Id(m.CsName)}({string.Join(", ", callArgs)})";
                _c.Open($"public {st}void {Id(m.CsName)}<{tp}>({string.Join(", ", given.Select(p => NoDefault(ParamDecl(m, p))).Append($"global::System.Collections.Generic.List<{tp}> results"))}){where}");
                _c.Line("if (results == null)");
                _c.Line("    throw new global::System.ArgumentNullException(nameof(results));");
                _c.Line("results.Clear();");
                _c.Line($"foreach (var hx_e in {listCall})");
                _c.Line($"    results.Add(({tp})(object)hx_e);");
                _c.Close();
            }
        }
    }

