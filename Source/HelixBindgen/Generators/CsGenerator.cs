    sealed class EventAbi
    {
        public readonly List<string> Abi = new();
        public readonly List<string> Params = new();
        public readonly List<string> Values = new();
        public readonly List<string> Types = new();
    }

    EventAbi EventSignature(TypeModel t, EventModel e) => Signature(e.Arguments, e.Where, $"{t.Name}.{e.CsName}");

    // The C# side of C++ values handed to a C# function (as CppGenerator.ToManaged hands them).
    EventAbi Signature(List<TypeRef> types, Location where, string what)
    {
        var a = new EventAbi();
        for (int i = 0; i < types.Count; i++)
        {
            Mapping m = _b.Map.Map(types[i], where, what);
            if (m.ByRef)
                throw new BindgenException(where, $"{what}: a C# override or implementation takes no ref or out arguments");
            string n = $"a{i}";
            a.Types.Add(CsType(m));
            switch (m.Kind)
            {
                case MapKind.Primitive or MapKind.Enum:
                    a.Abi.Add(CsType(m));
                    a.Params.Add($"{CsType(m)} {n}");
                    a.Values.Add(n);
                    break;
                case MapKind.Bool:
                    a.Abi.Add("byte");
                    a.Params.Add($"byte {n}");
                    a.Values.Add($"{n} != 0");
                    break;
                case MapKind.TypeId:
                    a.Abi.Add("uint");
                    a.Params.Add($"uint {n}");
                    a.Values.Add($"global::Helix.Interop.Types.FromNative({n})");
                    break;
                case MapKind.Struct:
                    a.Abi.Add(CsType(m) + "*");
                    a.Params.Add($"{CsType(m)}* {n}");
                    a.Values.Add($"*{n}");
                    break;
                case MapKind.String:
                    a.Abi.Add("byte*");
                    a.Abi.Add("int");
                    a.Params.Add($"byte* {n}");
                    a.Params.Add($"int {n}_n");
                    a.Values.Add($"global::Helix.Interop.Native.ReadString({n}, {n}_n)");
                    break;
                case MapKind.Object:
                    a.Abi.Add("ulong");
                    a.Abi.Add("uint");
                    a.Params.Add($"ulong {n}");
                    a.Params.Add($"uint {n}_t");
                    a.Values.Add($"global::Helix.Interop.Objects.Wrap<{CsType(m)}>({n}, {n}_t)");
                    break;
                case MapKind.Array:
                {
                    Mapping el = m.Element!;
                    string p = el.Kind == MapKind.Object ? "global::Helix.Interop.InteropObject*" : CsValue(el) + "*";
                    a.Abi.Add(p);
                    a.Abi.Add("int");
                    a.Params.Add($"{p} {n}");
                    a.Params.Add($"int {n}_n");
                    a.Values.Add(el.Kind == MapKind.Object
                        ? $"global::Helix.Interop.Objects.WrapArray<{CsType(el)}>({n}, {n}_n)"
                        : $"global::Helix.Interop.Native.ReadArray<{CsValue(el)}>({n}, {n}_n)");
                    break;
                }
            }
        }
        return a;
    }

    string DelegateType(EventModel e, EventAbi a)
    {
        string? named = e.Tag.Get("Delegate");
        if (named != null)
            return named;
        if (e.Query)
            return "global::System.Func<" + string.Join(", ", a.Types.Append("bool")) + ">";
        return a.Types.Count == 0 ? "global::System.Action" : "global::System.Action<" + string.Join(", ", a.Types) + ">";
    }

    readonly List<string> _callbacks = new();

    void WriteEvent(TypeModel t, Thunk add)
    {
        EventModel e = add.Event!;
        Thunk remove = _b.Thunks.First(x => x.Kind == ThunkKind.EventRemove && x.Event == e);
        int k = _events.Count;
        _events[e] = k;
        EventAbi a = EventSignature(t, e);
        string del = DelegateType(e, a);
        string self = add.Static ? "0ul" : "m_HxId";
        string callbackFn = $"delegate* unmanaged[Cdecl]<global::System.IntPtr{string.Join("", a.Abi.Select(x => ", " + x))}, {(e.Query ? "byte" : "void")}>";
        string what = $"{t.Name}.{e.CsName}";
        Attributes(e.Tag);
        _c.Open($"public {(add.Static ? "static " : "")}event {del} {Id(e.CsName)}");
        _c.Open("add");
        _c.Line("if (value == null)");
        _c.Line("    return;");
        _c.Line("var hx_gc = global::System.Runtime.InteropServices.GCHandle.Alloc(value);");
        _c.Line("uint hx_id;");
        _c.Line("void* hx_h;");
        string selfArg = add.Static ? "" : "m_HxId, ";
        _c.Line($"int hx_s = {ModuleClass}.{add.Name}({selfArg}(void*)({callbackFn})&{ModuleClass}.HxOn{k}, " +
                "(void*)global::System.Runtime.InteropServices.GCHandle.ToIntPtr(hx_gc), &hx_id, &hx_h);");
        _c.Open("if (hx_s != 0)");
        _c.Line("hx_gc.Free();");
        _c.Line($"global::Helix.Interop.Native.Fail(hx_s, \"{what}\");");
        _c.Close();
        _c.Line($"global::Helix.Interop.Events.Add({self}, {k}, value, hx_id, (global::System.IntPtr)hx_h, hx_gc);");
        _c.Close();
        _c.Open("remove");
        _c.Line($"if (value == null || !global::Helix.Interop.Events.Take({self}, {k}, value, out uint hx_id, out global::System.IntPtr hx_h, out var hx_gc))");
        _c.Line("    return;");
        _c.Line($"{ModuleClass}.{remove.Name}({selfArg}hx_id, (void*)hx_h);");
        _c.Line("hx_gc.Free();");
        _c.Close();
        _c.Close();
        var abiAdd = new List<string>();
        if (!add.Static)
            abiAdd.Add("ulong");
        abiAdd.AddRange(new[] { "void*", "void*", "uint*", "void**", "int" });
        _fnTypes[add] = $"delegate* unmanaged[Cdecl]<{string.Join(", ", abiAdd)}>";
        var abiRemove = new List<string>();
        if (!add.Static)
            abiRemove.Add("ulong");
        abiRemove.AddRange(new[] { "uint", "void*", "int" });
        _fnTypes[remove] = $"delegate* unmanaged[Cdecl]<{string.Join(", ", abiRemove)}>";

        // The callback native code calls: the delegate from its GC handle, exceptions reported (they never cross).
        var cb = new Code();
        cb.Line("[global::System.Runtime.InteropServices.UnmanagedCallersOnly(CallConvs = new[] { typeof(global::System.Runtime.CompilerServices.CallConvCdecl) })]");
        cb.Open($"internal static {(e.Query ? "byte" : "void")} HxOn{k}(global::System.IntPtr user{string.Join("", a.Params.Select(x => ", " + x))})");
        cb.Open("try");
        string invoke = $"(({del})global::System.Runtime.InteropServices.GCHandle.FromIntPtr(user).Target)({string.Join(", ", a.Values)})";
        cb.Line(e.Query ? $"return {invoke} ? (byte)1 : (byte)0;" : invoke + ";");
        cb.Close();
        cb.Open("catch (global::System.Exception hx_e)");
        cb.Line("global::Helix.Interop.Native.ReportException(hx_e);");
        if (e.Query)
            cb.Line("return 1;");
        cb.Close();
        cb.Close();
        _callbacks.Add(cb.ToString());
    }

