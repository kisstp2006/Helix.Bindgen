using Helix.Bindgen.Model;

namespace Helix.Bindgen.Generators;

/// <summary>
/// The C++ side of a module: the layout checks of its structs and enums, its types registered in the scripting core
/// (members with invokers on Variants), and the extern "C" thunks of the function table that C# calls.
/// </summary>
public sealed class CppGenerator
{
    // Helix's aliases of the primitives (namespace helix).
    static readonly HashSet<string> HelixAliases = new() { "i8", "u8", "i16", "u16", "i32", "u32", "i64", "u64", "f32", "f64" };

    readonly Binding _b;
    readonly Code _c = new();
    readonly Dictionary<FieldModel, int> _privateTags = new();
    readonly Dictionary<EventModel, int> _events = new();

    CppGenerator(Binding binding) => _b = binding;

    public static string Generate(Binding binding, IEnumerable<string> includes, string moduleKind)
    {
        var g = new CppGenerator(binding);
        g.Write(includes.ToList(), moduleKind);
        return g._c.ToString();
    }

    string ModuleIdent => _b.Ident(_b.Module.Name);
    IEnumerable<TypeModel> Own => _b.Module.Types.Where(t => !t.External);

    // ------------------------------------------------------------------------------------------- C++ spellings

    static string Q(TypeModel t) => "::" + t.CppName;

    string PrimitiveName(string name) => HelixAliases.Contains(name) ? "::helix::" + name
                                         : name.StartsWith("std::", StringComparison.Ordinal) ? "::" + name
                                         : name.StartsWith("helix::", StringComparison.Ordinal) ? "::" + name
                                         : name;

    /// <summary>A declared type spelled with qualified names (for the callbacks of events).</summary>
    string Spell(TypeRef t, Location where, string what)
    {
        Mapping m = _b.Map.Map(t, where, what);
        string name = m.Kind switch
        {
            MapKind.Void => "void",
            MapKind.Bool => "bool",
            MapKind.Primitive => PrimitiveName(t.Name),
            MapKind.String => t.Name.EndsWith("StringView", StringComparison.Ordinal) ? "::helix::StringView" : "::helix::String",
            MapKind.TypeId => "::helix::scripting::TypeId",
            MapKind.Array => (t.Name.EndsWith("Span", StringComparison.Ordinal) ? "::helix::Span<" : "::helix::Array<") +
                             string.Join(", ", t.Arguments.Select(a => Spell(a, where, what))) + ">",
            _ => Q(m.Bound!),
        };
        return (t.Const ? "const " : "") + name + new string('*', t.Pointers) + (t.Reference ? "&" : "");
    }

    /// <summary>The C++ type that holds a value of the mapping.</summary>
    string CType(Mapping m) => m.Kind switch
    {
        MapKind.Void => "void",
        MapKind.Bool => "bool",
        MapKind.Primitive => PrimitiveName(m.CppBare),
        MapKind.String => "::helix::String",
        MapKind.TypeId => "::helix::scripting::TypeId",
        MapKind.Object => Q(m.Bound!) + "*",
        MapKind.Array => "::helix::Array<" + CType(m.Element!) + ">",
        _ => Q(m.Bound!),
    };

    /// <summary>The registry's TypeId of the mapping, as an expression.</summary>
    string TypeExpr(Mapping m) => m.Kind switch
    {
        MapKind.Void => "TypeId()",
        MapKind.Object => $"TypeOf<{Q(m.Bound!)}>()",
        MapKind.Array => $"ArrayOf({TypeExpr(m.Element!)})",
        _ => $"TypeOf<{CType(m)}>()",
    };

    string RootName(Mapping m) => Q(_b.RootOf(m.Bound!));

    // ------------------------------------------------------------------------------------------- the file

    void Write(List<string> includes, string moduleKind)
    {
        _c.Line("// Generated by Helix.Bindgen. Do not edit.");
        _c.Line("#include <Helix/Scripting/Bindings/Interop.h>");
        _c.Line("#include <Helix/Scripting/Bindings/Marshal.h>");
        _c.Line("#include <Helix/Scripting/Types/TypeBuilder.h>");
        _c.Line();
        foreach (string inc in includes)
            _c.Line($"#include {inc}");
        _c.Line();
        _c.Line("#include <bit>");
        _c.Line("#include <cstddef>");
        _c.Line("#include <type_traits>");
        _c.Line();
        WriteLayoutChecks();
        _c.Open("namespace");
        _c.Line("using namespace ::helix;");
        _c.Line("using namespace ::helix::scripting;");
        _c.Line();
        WritePrivateAccess();
        foreach (Thunk th in _b.Thunks)
            WriteThunk(th);
        WriteTable();
        _c.Close("}");
        _c.Line();
        WriteRegister(moduleKind);
    }

    void WriteLayoutChecks()
    {
        foreach (TypeModel t in Own)
        {
            if (t.Kind == TypeKind.Struct)
            {
                (int size, int align) = _b.Map.Layout(t);
                _c.Line($"static_assert(sizeof({Q(t)}) == {size} && alignof({Q(t)}) == {align}, \"{t.Name}: the layout C# was given\");");
                foreach (FieldModel f in t.Fields.Where(f => !f.Static))
                    _c.Line($"static_assert(offsetof({Q(t)}, {f.Name}) == {_b.Map.FieldOffset(t, f)}, \"{t.Name}.{f.Name}: the offset C# was given\");");
            }
            else if (t.Kind == TypeKind.Enum)
            {
                (int size, _) = _b.Map.EnumSize(t);
                _c.Line($"static_assert(sizeof({Q(t)}) == {size}, \"{t.Name}: the size C# was given\");");
                foreach (EnumValueModel v in t.EnumValues)
                    _c.Line($"static_assert(static_cast<long long>({Q(t)}::{v.Name}) == {v.Value}ll, \"{t.Name}.{v.Name}: the value C# was given\");");
            }
        }
        _c.Line();
    }

    // Private serialized fields: their member pointers through explicit instantiation (which does not check access).
    void WritePrivateAccess()
    {
        var fields = Own.SelectMany(t => t.Fields.Where(f => f.Tag.Has("Private") && !f.Static).Select(f => (t, f))).ToList();
        if (fields.Count == 0)
            return;
        _c.Line("template <class Tag, typename Tag::Type Member>");
        _c.Open("struct HxAccess");
        _c.Line("friend typename Tag::Type HxMember(Tag) { return Member; }");
        _c.Close("};");
        foreach ((TypeModel t, FieldModel f) in fields)
        {
            int k = _privateTags.Count;
            _privateTags[f] = k;
            _c.Open($"struct HxTag{k}");
            _c.Line($"using Type = {Spell(f.Type, f.Where, f.Name)} ({Q(t)}::*);");
            _c.Line($"friend Type HxMember(HxTag{k});");
            _c.Close("};");
            _c.Line($"template struct HxAccess<HxTag{k}, &{Q(t)}::{f.Name}>;");
        }
        _c.Line();
    }

    string MemberPointer(TypeModel t, FieldModel f) => _privateTags.TryGetValue(f, out int k) ? $"HxMember(HxTag{k}{{}})" : $"&{Q(t)}::{f.Name}";

    string Access(TypeModel t, FieldModel f, string self) =>
        f.Static ? $"{Q(t)}::{f.Name}"
        : _privateTags.TryGetValue(f, out int k) ? $"({self}->*HxMember(HxTag{k}{{}}))"
        : $"{self}->{f.Name}";

    // ------------------------------------------------------------------------------------------- thunks

    sealed class Call
    {
        public readonly List<string> Params = new();
        public readonly List<string> Prep = new();
        public readonly List<string> Args = new();
        public readonly List<string> Post = new();
    }

    // A value going in: its C parameters, the lines that make the C++ value, and the argument.
    void In(Call call, Mapping m, string n, TypeRef declared)
    {
        if (m.ByRef)
        {
            switch (m.Kind)
            {
                case MapKind.Object:
                    call.Params.Add($"InteropObject* {n}");
                    call.Prep.Add($"{CType(m)} {n}_o = nullptr;");
                    call.Args.Add($"{n}_o");
                    call.Post.Add($"*{n} = PassObject<{RootName(m)}>({n}_o);");
                    return;
                case MapKind.Primitive or MapKind.Bool or MapKind.Enum or MapKind.Struct:
                    call.Params.Add($"{CType(m)}* {n}");
                    call.Args.Add(declared.Pointers > 0 ? n : $"*{n}");
                    return;
                default:
                    throw new BindgenException(new Location(), $"{n}: {m.Cs} is not passed by reference");
            }
        }
        switch (m.Kind)
        {
            case MapKind.Primitive:
            case MapKind.Enum:
                call.Params.Add($"{CType(m)} {n}");
                call.Args.Add(n);
                break;
            case MapKind.Bool:
                call.Params.Add($"u8 {n}");
                call.Args.Add($"{n} != 0");
                break;
            case MapKind.TypeId:
                call.Params.Add($"u32 {n}");
                call.Args.Add($"TypeId{{{n}}}");
                break;
            case MapKind.Struct:
                call.Params.Add($"const {CType(m)}* {n}");
                call.Args.Add(declared.Pointers > 0 ? n : $"*{n}");
                break;
            case MapKind.String:
                call.Params.Add($"const char16_t* {n}");
                call.Params.Add($"i32 {n}_n");
                call.Prep.Add($"String {n}_s = StringFromUtf16({n}, {n}_n);");
                call.Args.Add($"{n}_s");
                break;
            case MapKind.Object:
                call.Params.Add($"u64 {n}");
                call.Prep.Add($"{CType(m)} {n}_o = ObjectFromId<{RootName(m)}, {Q(m.Bound!)}>({n});");
                if (declared.Reference && declared.Pointers == 0)
                {
                    call.Prep.Add($"if (!{n}_o)");
                    call.Prep.Add("    return InteropNullArgument;");
                    call.Args.Add($"*{n}_o");
                }
                else
                    call.Args.Add($"{n}_o");
                break;
            case MapKind.Array:
            {
                Mapping e = m.Element!;
                string et = CType(e);
                if (e.Kind == MapKind.Object)
                {
                    call.Params.Add($"const u64* {n}");
                    call.Params.Add($"i32 {n}_n");
                    call.Prep.Add($"Array<{et}> {n}_a;");
                    call.Prep.Add($"{n}_a.Reserve(usize({n}_n));");
                    call.Prep.Add($"for (i32 i = 0; i < {n}_n; i++)");
                    call.Prep.Add($"    {n}_a.Push(ObjectFromId<{RootName(e)}, {Q(e.Bound!)}>({n}[i]));");
                    call.Args.Add($"{n}_a");
                }
                else
                {
                    call.Params.Add($"const {et}* {n}");
                    call.Params.Add($"i32 {n}_n");
                    if (declared.Name.EndsWith("Span", StringComparison.Ordinal))
                        call.Args.Add($"Span<const {et}>({n}, usize({n}_n))");
                    else
                    {
                        call.Prep.Add($"Array<{et}> {n}_a;");
                        call.Prep.Add($"{n}_a.Reserve(usize({n}_n));");
                        call.Prep.Add($"for (i32 i = 0; i < {n}_n; i++)");
                        call.Prep.Add($"    {n}_a.Push({n}[i]);");
                        call.Args.Add($"{n}_a");
                    }
                }
                break;
            }
            default:
                throw new BindgenException(new Location(), $"{n}: {m.Cs} does not go in");
        }
    }

    string OutParam(Mapping m) => m.Kind switch
    {
        MapKind.Bool => "u8* result",
        MapKind.TypeId => "u32* result",
        MapKind.String => "InteropString* result",
        MapKind.Object => "InteropObject* result",
        MapKind.Array => "InteropArray* result",
        _ => $"{CType(m)}* result",
    };

    // The lines that hand a C++ value out through `result`.
    List<string> Out(Mapping m, string expr, TypeRef declared)
    {
        switch (m.Kind)
        {
            case MapKind.Bool:
                return new() { $"*result = ({expr}) ? 1 : 0;" };
            case MapKind.TypeId:
                return new() { $"*result = ({expr}).value;" };
            case MapKind.String:
                return new() { $"*result = PassString({expr});" };
            case MapKind.Object:
                return new() { declared.Reference && declared.Pointers == 0 ? $"*result = PassObject<{RootName(m)}>(&({expr}));" : $"*result = PassObject<{RootName(m)}>({expr});" };
            case MapKind.Array:
            {
                Mapping e = m.Element!;
                if (e.Kind == MapKind.Object)
                    return new()
                    {
                        $"auto&& v = {expr};",
                        "Array<InteropObject> ids;",
                        "ids.Reserve(v.Size());",
                        "for (auto* o : v)",
                        $"    ids.Push(PassObject<{RootName(e)}>(o));",
                        "*result = PassArray(ids.Data(), sizeof(InteropObject), ids.Size());",
                    };
                return new() { $"auto&& v = {expr};", $"*result = PassArray(v.Data(), sizeof({CType(e)}), v.Size());" };
            }
            default:
                return new() { $"*result = {expr};" };
        }
    }

    string Self(TypeModel t) => $"{Q(t)}* self_o = ObjectFromId<{Q(_b.RootOf(t))}, {Q(t)}>(self);";

    void WriteThunk(Thunk th)
    {
        TypeModel t = th.Owner;
        var call = new Call();
        if (!th.Static)
        {
            call.Params.Add("u64 self");
            call.Prep.Add(Self(t));
            call.Prep.Add("if (!self_o)");
            call.Prep.Add("    return InteropMissingObject;");
        }
        string target = th.Static ? $"{Q(t)}::" : "self_o->";
        List<string> body;
        switch (th.Kind)
        {
            case ThunkKind.FieldGet:
                call.Params.Add(OutParam(th.Type));
                body = Out(th.Type, Access(t, th.Field!, "self_o"), th.Field!.Type);
                break;
            case ThunkKind.FieldSet:
            {
                var value = new Call();
                Mapping m = th.Type;
                // A field is set from a value (not through a pointer or reference).
                In(value, new Mapping { Kind = m.Kind, Cs = m.Cs, CppBare = m.CppBare, Size = m.Size, Align = m.Align, Element = m.Element, Bound = m.Bound },
                   "value", th.Field!.Type.Bare());
                call.Params.AddRange(value.Params);
                call.Prep.AddRange(value.Prep);
                body = new() { $"{Access(t, th.Field!, "self_o")} = {value.Args[0]};" };
                break;
            }
            case ThunkKind.Method:
            {
                MethodModel mm = th.Method!;
                foreach (ParameterModel p in mm.Parameters)
                    In(call, _b.Map.Map(p.Type, mm.Where, $"{t.Name}.{mm.Name}({p.Name})"), "p_" + p.Name, p.Type);
                string expr = $"{target}{mm.Name}({string.Join(", ", call.Args)})";
                if (th.Type.Kind == MapKind.Void)
                    body = new() { expr + ";" };
                else
                {
                    call.Params.Add(OutParam(th.Type));
                    body = Out(th.Type, expr, mm.Return);
                }
                break;
            }
            case ThunkKind.EventAdd:
                WriteEventAdapter(th.Event!, t);
                call.Params.AddRange(new[] { "void* fn", "void* user", "u32* id", "void** handle" });
                body = new()
                {
                    $"auto* h = new HxHandler{_events[th.Event!]}{{std::bit_cast<decltype(HxHandler{_events[th.Event!]}::fn)>(fn), user}};",
                    $"*id = {EventExpr(th.Event!, t, "self_o")}.Add(&HxAdapter{_events[th.Event!]}, h);",
                    "*handle = h;",
                };
                break;
            case ThunkKind.EventRemove:
            {
                int k = _events[th.Event!];
                call.Params.AddRange(new[] { "u32 id", "void* handle" });
                call.Prep.Clear();
                var lines = new List<string>();
                if (!th.Static)
                {
                    lines.Add(Self(t));
                    lines.Add("if (self_o)");
                    lines.Add($"    {EventExpr(th.Event!, t, "self_o")}.Remove(id);");
                    lines.Add($"delete static_cast<HxHandler{k}*>(handle);");
                    lines.Add("return self_o ? InteropOk : InteropMissingObject;");
                }
                else
                {
                    lines.Add($"{EventExpr(th.Event!, t, "self_o")}.Remove(id);");
                    lines.Add($"delete static_cast<HxHandler{k}*>(handle);");
                    lines.Add("return InteropOk;");
                }
                _c.Open($"i32 {th.Name}({string.Join(", ", call.Params)})");
                foreach (string l in lines)
                    _c.Line(l);
                _c.Close();
                _c.Line();
                return;
            }
            default:
                throw new InvalidOperationException();
        }
        _c.Open($"i32 {th.Name}({string.Join(", ", call.Params)})");
        foreach (string l in call.Prep)
            _c.Line(l);
        foreach (string l in body)
            _c.Line(l);
        foreach (string l in call.Post)
            _c.Line(l);
        _c.Line("return InteropOk;");
        _c.Close();
        _c.Line();
    }

    string EventExpr(EventModel e, TypeModel t, string self) =>
        (e.Static ? $"{Q(t)}::{e.Member}" : $"{self}->{e.Member}") + (e.IsFunction ? "()" : "");

    // The handler of an event from C# (its function pointer and GC handle) and the C++ callback that converts the
    // event's arguments for it.
    void WriteEventAdapter(EventModel e, TypeModel t)
    {
        int k = _events.Count;
        _events[e] = k;
        var abi = new List<string>();
        var spelled = new List<string>();
        var prep = new List<string>();
        var args = new List<string>();
        for (int i = 0; i < e.Arguments.Count; i++)
        {
            TypeRef a = e.Arguments[i];
            Mapping m = _b.Map.Map(a, e.Where, $"{t.Name}.{e.CsName}");
            string n = $"a{i}";
            spelled.Add($"{Spell(a, e.Where, e.CsName)} {n}");
            bool isPointer = a.Pointers > 0;
            switch (m.Kind)
            {
                case MapKind.Primitive or MapKind.Enum:
                    abi.Add(CType(m));
                    args.Add(isPointer ? $"*{n}" : n);
                    break;
                case MapKind.Bool:
                    abi.Add("u8");
                    args.Add($"{n} ? 1 : 0");
                    break;
                case MapKind.TypeId:
                    abi.Add("u32");
                    args.Add($"{n}.value");
                    break;
                case MapKind.Struct:
                    abi.Add($"const {CType(m)}*");
                    args.Add(isPointer ? n : $"&{n}");
                    break;
                case MapKind.String:
                    abi.Add("const char*");
                    abi.Add("i32");
                    prep.Add($"StringView {n}_v = {n};");
                    args.Add($"{n}_v.Data()");
                    args.Add($"i32({n}_v.Size())");
                    break;
                case MapKind.Object:
                    abi.Add("u64");
                    abi.Add("u32");
                    prep.Add($"InteropObject {n}_o = PassObject<{RootName(m)}>({(isPointer ? n : "&" + n)});");
                    args.Add($"{n}_o.id");
                    args.Add($"{n}_o.type");
                    break;
                case MapKind.Array:
                {
                    Mapping el = m.Element!;
                    abi.Add(el.Kind == MapKind.Object ? "const InteropObject*" : $"const {CType(el)}*");
                    abi.Add("i32");
                    if (el.Kind == MapKind.Object)
                    {
                        prep.Add($"Array<InteropObject> {n}_ids;");
                        prep.Add($"for (auto* o : {n})");
                        prep.Add($"    {n}_ids.Push(PassObject<{RootName(el)}>(o));");
                        args.Add($"{n}_ids.Data()");
                        args.Add($"i32({n}_ids.Size())");
                    }
                    else
                    {
                        args.Add($"{n}.Data()");
                        args.Add($"i32({n}.Size())");
                    }
                    break;
                }
                default:
                    throw new BindgenException(e.Where, $"{t.Name}.{e.CsName}: an event argument of {m.Cs}");
            }
        }
        string abiList = string.Join("", abi.Select(x => ", " + x));
        _c.Open($"struct HxHandler{k}");
        _c.Line($"{(e.Query ? "u8" : "void")} (*fn)(void* user{abiList});");
        _c.Line("void* user;");
        _c.Close("};");
        _c.Open($"{(e.Query ? "bool" : "void")} HxAdapter{k}(void* p{string.Join("", spelled.Select(x => ", " + x))})");
        _c.Line($"auto* h = static_cast<HxHandler{k}*>(p);");
        foreach (string l in prep)
            _c.Line(l);
        string invoke = $"h->fn(h->user{string.Join("", args.Select(x => ", " + x))})";
        _c.Line(e.Query ? $"return {invoke} != 0;" : invoke + ";");
        _c.Close();
    }

    void WriteTable()
    {
        _c.Open("const void* const kHxFunctions[] =");
        foreach (Thunk th in _b.Thunks)
            _c.Line($"std::bit_cast<const void*>(&{th.Name}),");
        _c.Line("nullptr,");
        _c.Close("};");
        _c.Line($"u32 gHxTypes[{_b.Ordered().Count + 1}] = {{}};");
    }

    // ------------------------------------------------------------------------------------------- registration

    void WriteRegister(string moduleKind)
    {
        List<TypeModel> types = _b.Ordered();
        var ids = new Dictionary<TypeModel, string>();
        for (int i = 0; i < types.Count; i++)
            ids[types[i]] = $"t{i}";

        _c.Line($"// Registers the module's types in the scripting core (once) and its function table for C#.");
        _c.Open($"HX_BINDINGS_EXPORT bool HxBindings_{ModuleIdent}_Register()");
        _c.Line("using namespace ::helix;");
        _c.Line("using namespace ::helix::scripting;");
        _c.Line("static bool done = false;");
        _c.Line("if (done)");
        _c.Line("    return true;");
        _c.Line($"ModuleId mod = FindModule(\"{_b.Module.Name}\");");
        _c.Line("if (!mod.IsValid())");
        _c.Line($"    mod = RegisterModule(\"{_b.Module.Name}\", ModuleKind::{moduleKind});");
        foreach (TypeModel t in types)
        {
            TypeModel? baseModel = t.Kind == TypeKind.Class ? _b.BaseOf(t) : null;
            string baseExpr = baseModel == null ? "TypeId()" : ids.TryGetValue(baseModel, out string? bid) ? bid : $"TypeOf<{Q(baseModel)}>()";
            string kind = t.Kind switch { TypeKind.Class => "Class", TypeKind.Struct => "Struct", TypeKind.Enum => "Enum", _ => "Interface" };
            string flags = t.Kind is TypeKind.Class or TypeKind.Interface
                ? $"(std::is_abstract_v<{Q(t)}> ? u32(TypeAbstract) : 0u){(t.Tag.Has("Sealed") ? " | u32(TypeSealed)" : "")}"
                : "TypeNone";
            _c.Line($"TypeId {ids[t]} = DeclareType(mod, \"{t.CsNamespace}\", \"{t.RegistryName}\", TypeKind::{kind}, {baseExpr}, {flags});");
            _c.Line($"if (!{ids[t]}.IsValid())");
            _c.Line("    return false;");
            _c.Line($"BindNativeType<{Q(t)}>({ids[t]});");
            _c.Line($"gHxTypes[{types.IndexOf(t)}] = {ids[t]}.value;");
        }
        foreach (TypeModel t in types)
            WriteBuilder(t, ids[t]);
        _c.Line($"RegisterNativeFunctions(\"{_b.Module.Name}\", kHxFunctions, {_b.Thunks.Count}u);");
        _c.Line("done = true;");
        _c.Line("return true;");
        _c.Close();
        _c.Line();
        _c.Line("// The function table and the hash of its shape (the C# side checks both).");
        _c.Open($"HX_BINDINGS_EXPORT const void* const* HxBindings_{ModuleIdent}_Functions(::helix::u32* count, ::helix::u64* hash)");
        _c.Line($"*count = {_b.Thunks.Count}u;");
        _c.Line($"*hash = 0x{_b.Hash:x16}ull;");
        _c.Line("return kHxFunctions;");
        _c.Close();
        _c.Line();
        _c.Line("// The registered ids of the module's types, in the order the C# side lists them (valid after Register).");
        _c.Open($"HX_BINDINGS_EXPORT const ::helix::u32* HxBindings_{ModuleIdent}_Types(::helix::u32* count)");
        _c.Line($"*count = {types.Count}u;");
        _c.Line("return gHxTypes;");
        _c.Close();
    }

    void WriteBuilder(TypeModel t, string id)
    {
        _c.Open();
        _c.Line($"TypeBuilder b({id});");
        bool objectClass = _b.IsObjectClass(t);
        if (t.Kind == TypeKind.Interface || objectClass)
            _c.Line($"b.Size(u32(sizeof({Q(t)})), u32(alignof({Q(t)})));");
        else
            _c.Line($"b.Native<{Q(t)}>();");
        foreach (TypeModel i in _b.InterfacesOf(t))
            _c.Line($"b.Interface(TypeOf<{Q(i)}>());");
        if (t.Kind == TypeKind.Enum)
        {
            _c.Line($"b.Underlying(TypeOf<std::underlying_type_t<{Q(t)}>>());");
            foreach (EnumValueModel v in t.EnumValues)
                _c.Line($"b.EnumValue(\"{v.Name}\", {v.Value}ll);");
        }
        foreach (FieldModel f in t.Fields)
            WriteField(t, f);
        foreach (PropertyModel p in t.Properties)
        {
            Mapping m = _b.Map.Map(p.Getter.Return, p.Getter.Where, $"{t.Name}.{p.CsName}");
            string flags = Flags(public_: true, p.Static, readOnly: p.Setter == null);
            _c.Line($"b.Property(\"{p.CsName}\", {TypeExpr(m)},");
            _c.Line($"           {Invoker(t, p.Getter)},");
            _c.Line($"           {(p.Setter != null ? Invoker(t, p.Setter) : "nullptr")}, nullptr, {flags});");
        }
        foreach (MethodModel mm in t.Methods)
        {
            Mapping r = _b.Map.Map(mm.Return, mm.Where, $"{t.Name}.{mm.Name}");
            string[] outs = (mm.Tag.Get("Out") ?? "").Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            var ps = mm.Parameters.Select(p =>
            {
                Mapping pm = _b.Map.Map(p.Type, mm.Where, p.Name);
                var pf = new List<string>();
                if (outs.Contains(p.Name))
                    pf.Add("ParameterOut");
                else if (pm.ByRef)
                    pf.Add("ParameterRef");
                if (p.Default != null)
                    pf.Add("ParameterOptional");
                string pflags = pf.Count == 0 ? "ParameterNone" : string.Join(" | ", pf.Select(x => $"u32({x})"));
                return $"ParameterInfo{{\"{p.Name}\", {TypeExpr(pm)}, {pflags}}}";
            }).ToList();
            string list = ps.Count == 0 ? "std::initializer_list<ParameterInfo>{}" : "{" + string.Join(", ", ps) + "}";
            var mf = new List<string> { "u32(MemberPublic)" };
            if (mm.Static || mm.Tag.Has("Constructor"))
                mf.Add("u32(MemberStatic)");
            if (mm.Virtual)
                mf.Add("u32(MemberVirtual)");
            if (mm.Tag.Has("Constructor"))
                mf.Add("u32(MemberConstructor)");
            _c.Line($"b.Method(\"{mm.CsName}\", {TypeExpr(r)}, {list},");
            _c.Line($"         {Invoker(t, mm)}, nullptr, {string.Join(" | ", mf)});");
        }
        foreach (EventModel e in t.Events)
            WriteReflectedEvent(t, e);
        _c.Line("b.Finish();");
        _c.Close();
    }

    static string Flags(bool public_, bool isStatic, bool readOnly, bool serialized = false)
    {
        var f = new List<string>();
        if (public_)
            f.Add("u32(MemberPublic)");
        if (isStatic)
            f.Add("u32(MemberStatic)");
        if (readOnly)
            f.Add("u32(MemberReadOnly)");
        if (serialized)
            f.Add("u32(MemberSerialized)");
        return f.Count == 0 ? "u32(MemberNone)" : string.Join(" | ", f);
    }

    string ToVariantExpr(Mapping m, string expr, TypeRef declared)
    {
        if (m.Kind == MapKind.Object)
            return $"ObjectToVariant<{RootName(m)}>({(declared.Reference && declared.Pointers == 0 ? $"&({expr})" : expr)})";
        return $"ToVariant({expr})";
    }

    void WriteField(TypeModel t, FieldModel f)
    {
        Mapping m = _b.Map.Map(f.Type, f.Where, $"{t.Name}.{f.Name}");
        bool readOnly = f.Type.Const || f.Tag.Has("ReadOnly");
        bool serialized = !f.Static && !readOnly && !f.Tag.Has("NonSerialized");
        string flags = Flags(!f.Tag.Has("Private"), f.Static, readOnly, serialized);
        bool plain = m.Kind is MapKind.Primitive or MapKind.Bool or MapKind.Enum or MapKind.Struct ||
                     (m.Kind == MapKind.String && !f.Type.Name.EndsWith("StringView", StringComparison.Ordinal));
        if (plain && !f.Static && f.Type.Pointers == 0 && !f.Type.Reference)
        {
            _c.Line($"b.Field(\"{f.CsName}\", {TypeExpr(m)}, OffsetOf({MemberPointer(t, f)}), {flags});");
            return;
        }
        string self = f.Static ? "" : $"const {Q(t)}* self_o = static_cast<const {Q(t)}*>(instance); ";
        string instParam = f.Static ? "const void*" : "const void* instance";
        _c.Line($"b.Field(\"{f.CsName}\", {TypeExpr(m)},");
        _c.Line($"        [](const void*, {instParam}, Variant& out, String&) -> bool {{ {self}out = {ToVariantExpr(m, Access(t, f, "self_o"), f.Type)}; return true; }},");
        if (readOnly)
            _c.Line("        nullptr,");
        else
        {
            string mself = f.Static ? "" : $"{Q(t)}* self_o = static_cast<{Q(t)}*>(instance); ";
            string mParam = f.Static ? "void*" : "void* instance";
            _c.Line($"        [](const void*, {mParam}, const Variant& value, String& error) -> bool {{ {mself}if (FromVariant(value, {Access(t, f, "self_o")})) return true; " +
                    $"error = \"{t.Name}.{f.Name}: the value does not convert\"; return false; }},");
        }
        _c.Line($"        nullptr, {flags});");
    }

    // An invoker: the arguments from Variants into locals of the parameters' types, the call, the result.
    string Invoker(TypeModel t, MethodModel mm)
    {
        bool isStatic = mm.Static || mm.Tag.Has("Constructor");
        Mapping r = _b.Map.Map(mm.Return, mm.Where, $"{t.Name}.{mm.Name}");
        var lines = new List<string>();
        if (!isStatic)
        {
            lines.Add($"{Q(t)}* self_o = static_cast<{Q(t)}*>(instance);");
            lines.Add($"if (!self_o) {{ error = \"{t.Name}.{mm.Name}: no instance\"; return false; }}");
        }
        var args = new List<string>();
        for (int i = 0; i < mm.Parameters.Count; i++)
        {
            ParameterModel p = mm.Parameters[i];
            Mapping pm = _b.Map.Map(p.Type, mm.Where, p.Name);
            string n = $"a{i}";
            lines.Add($"{CType(pm)} {n}{{}};");
            lines.Add($"if (!FromVariant(args[{i}], {n})) {{ error = \"{t.Name}.{mm.Name}: the argument {p.Name}\"; return false; }}");
            if (pm.Kind == MapKind.Object && p.Type.Reference && p.Type.Pointers == 0)
            {
                lines.Add($"if (!{n}) {{ error = \"{t.Name}.{mm.Name}: {p.Name} is null\"; return false; }}");
                args.Add($"*{n}");
            }
            else if (pm.Kind == MapKind.Struct && p.Type.Pointers > 0)
                args.Add($"&{n}");
            else
                args.Add(n);
        }
        string call = (isStatic ? $"{Q(t)}::" : "self_o->") + $"{mm.Name}({string.Join(", ", args)})";
        if (r.Kind == MapKind.Void)
            lines.Add(call + ";");
        else
            lines.Add($"result = {ToVariantExpr(r, call, mm.Return)};");
        lines.Add("return true;");
        bool usesError = !isStatic || mm.Parameters.Count > 0;
        string sig = $"[](const void*, {(isStatic ? "void*" : "void* instance")}, {(mm.Parameters.Count > 0 ? "Span<const Variant> args" : "Span<const Variant>")}, " +
                     $"{(r.Kind == MapKind.Void ? "Variant&" : "Variant& result")}, {(usesError ? "String& error" : "String&")}) -> bool";
        return sig + " { " + string.Join(" ", lines) + " }";
    }

    void WriteReflectedEvent(TypeModel t, EventModel e)
    {
        string self = e.Static ? "" : $"{Q(t)}* self_o = static_cast<{Q(t)}*>(instance); if (!self_o) {{ error = \"{t.Name}.{e.CsName}: no instance\"; return false; }} ";
        string inst = e.Static ? "void*" : "void* instance";
        string ev = EventExpr(e, t, "self_o");
        string handler = "EventHandler h; if (!args[0].Get(h)) { error = \"" + t.Name + "." + e.CsName + ": not an EventHandler\"; return false; } " +
                         $"auto& ev = {ev}; using Ev = std::remove_cvref_t<decltype(ev)>; ";
        string add = $"[](const void*, {inst}, Span<const Variant> args, Variant&, String& error) -> bool {{ {self}{handler}" +
                     "ev.Add(std::bit_cast<typename Ev::Callback>(h.function), h.user); return true; }";
        string remove = $"[](const void*, {inst}, Span<const Variant> args, Variant&, String& error) -> bool {{ {self}{handler}" +
                        "ev.Remove(std::bit_cast<typename Ev::Callback>(h.function), h.user); return true; }";
        var lines = new List<string>();
        var callArgs = new List<string>();
        for (int i = 0; i < e.Arguments.Count; i++)
        {
            TypeRef a = e.Arguments[i];
            Mapping m = _b.Map.Map(a, e.Where, e.CsName);
            lines.Add($"{CType(m)} a{i}{{}};");
            lines.Add($"if (!FromVariant(args[{i}], a{i})) {{ error = \"{t.Name}.{e.CsName}: the argument {i}\"; return false; }}");
            callArgs.Add(m.Kind == MapKind.Object && a.Reference && a.Pointers == 0 ? $"*a{i}" : m.Kind == MapKind.Struct && a.Pointers > 0 ? $"&a{i}" : $"a{i}");
        }
        string fire = e.Query ? $"result = Variant::Bool({ev}.Ask({string.Join(", ", callArgs)}));" : $"{ev}.Invoke({string.Join(", ", callArgs)});";
        bool usesError = !e.Static || e.Arguments.Count > 0;
        string raise = $"[](const void*, {inst}, {(e.Arguments.Count > 0 ? "Span<const Variant> args" : "Span<const Variant>")}, {(e.Query ? "Variant& result" : "Variant&")}, " +
                       $"{(usesError ? "String& error" : "String&")}) -> bool {{ {self}{string.Join(" ", lines)} {fire} return true; }}";
        _c.Line($"b.Event(\"{e.CsName}\", EventHandlerType(),");
        _c.Line($"        {add},");
        _c.Line($"        {remove},");
        _c.Line($"        {raise}, nullptr, {Flags(true, e.Static, false)});");
    }
