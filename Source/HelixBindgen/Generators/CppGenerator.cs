using Helix.Bindgen.Model;

namespace Helix.Bindgen.Generators;

/// <summary>
/// The C++ side of a module: the layout checks of its structs and enums, its types registered in the scripting core
/// (members with invokers on Variants), and the extern "C" thunks of the function table that C# calls.
/// </summary>
public sealed class CppGenerator
{
    // Helix's aliases of the primitives (namespace helix).
    static readonly HashSet<string> HelixAliases = new() { "i8", "u8", "i16", "u16", "i32", "u32", "i64", "u64", "f32", "f64" };

    readonly Binding _b;
    readonly Code _c = new();
    readonly Dictionary<FieldModel, int> _privateTags = new();
    readonly Dictionary<EventModel, int> _events = new();

    CppGenerator(Binding binding) => _b = binding;

    public static string Generate(Binding binding, IEnumerable<string> includes, string moduleKind)
    {
        var g = new CppGenerator(binding);
        g.Write(includes.ToList(), moduleKind);
        return g._c.ToString();
    }

    string ModuleIdent => _b.Ident(_b.Module.Name);
    IEnumerable<TypeModel> Own => _b.Module.Types.Where(t => !t.External);

    // ------------------------------------------------------------------------------------------- C++ spellings

    static string Q(TypeModel t) => "::" + t.CppName;
    // The value handle of a class in the C++ script API.
    static string Handle(TypeModel t) => "::" + t.CsFullName.Replace(".", "::");

    string PrimitiveName(string name) => HelixAliases.Contains(name) ? "::helix::" + name
                                         : name.StartsWith("std::", StringComparison.Ordinal) ? "::" + name
                                         : name.StartsWith("helix::", StringComparison.Ordinal) ? "::" + name
                                         : name;

    /// <summary>A declared type spelled with qualified names (for the callbacks of events).</summary>
    string Spell(TypeRef t, Location where, string what)
    {
        string suffix = new string('*', t.Pointers) + (t.Reference ? "&" : "");
        if (_b.ValueHandle(t) is TypeModel handle)
            return (t.Const ? "const " : "") + Handle(handle) + suffix;
        if (_b.HoldsValueHandle(t))
            return (t.Const ? "const " : "") + "::helix::Array<" + Handle(_b.ValueHandle(t.Arguments[0])!) + ">" + suffix;
        Mapping m = _b.Map.Map(t, where, what);
        string name = m.Kind switch
        {
            MapKind.Void => "void",
            MapKind.Bool => "bool",
            MapKind.Primitive => PrimitiveName(t.Name),
            MapKind.String => t.Name.EndsWith("StringView", StringComparison.Ordinal) ? "::helix::StringView" : "::helix::String",
            MapKind.TypeId => "::helix::scripting::TypeId",
            MapKind.Array => (t.Name.EndsWith("Span", StringComparison.Ordinal) ? "::helix::Span<" : "::helix::Array<") +
                             string.Join(", ", t.Arguments.Select(a => Spell(a, where, what))) + ">",
            _ => Q(m.Bound!),
        };
        return (t.Const ? "const " : "") + name + new string('*', t.Pointers) + (t.Reference ? "&" : "");
    }

    /// <summary>The C++ type that holds a value of the mapping.</summary>
    string CType(Mapping m) => m.Kind switch
    {
        MapKind.Void => "void",
        MapKind.Bool => "bool",
        MapKind.Primitive => PrimitiveName(m.CppBare),
        MapKind.String => "::helix::String",
        MapKind.TypeId => "::helix::scripting::TypeId",
        MapKind.Object => Q(m.Bound!) + "*",
        MapKind.Array => "::helix::Array<" + CType(m.Element!) + ">",
        _ => Q(m.Bound!),
    };

    /// <summary>The registry's TypeId of the mapping, as an expression.</summary>
    string TypeExpr(Mapping m) => m.Kind switch
    {
        MapKind.Void => "TypeId()",
        MapKind.Object => $"TypeOf<{Q(m.Bound!)}>()",
        MapKind.Array => $"ArrayOf({TypeExpr(m.Element!)})",
        _ => $"TypeOf<{CType(m)}>()",
    };

    string RootName(Mapping m) => Q(_b.RootOf(m.Bound!));

    // ------------------------------------------------------------------------------------------- the file

    void Write(List<string> includes, string moduleKind)
    {
        _c.Line("// Generated by Helix.Bindgen. Do not edit.");
        _c.Line("#include <Helix/Scripting/Bindings/Interop.h>");
        _c.Line("#include <Helix/Scripting/Bindings/Marshal.h>");
        _c.Line("#include <Helix/Scripting/Types/TypeBuilder.h>");
        _c.Line("#include <Helix/Scripting/Scripts/NativeScript.h>");
        CollectSerialization();
        if (_transfers.Count > 0)
            _c.Line("#include <Helix/Serialization/Transfer/Dynamic.h>");
        _c.Line();
        foreach (string inc in includes)
            _c.Line($"#include {inc}");
        _c.Line();
        _c.Line("#include <bit>");
        _c.Line("#include <cstddef>");
        _c.Line("#include <cstring>");
        _c.Line("#include <new>");
        _c.Line("#include <type_traits>");
        _c.Line();
        WriteLayoutChecks();
        _c.Open("namespace");
        _c.Line("using namespace ::helix;");
        _c.Line("using namespace ::helix::scripting;");
        _c.Line();
        WritePrivateAccess();
        if (_transfers.Count > 0)
        {
            _c.Close("}");
            _c.Line();
            WriteSerializationTraits();
            _c.Open("namespace");
            _c.Line("using namespace ::helix;");
            _c.Line("using namespace ::helix::scripting;");
            _c.Line();
            WriteScriptTransfers();
        }
        WriteBridge();
        _c.Line("// A value of an 8 byte slot of a thunk with many parameters (its bytes from the first).");
        _c.Line("template <class T>");
        _c.Open("[[maybe_unused]] T HxSlot(u64 slot)");
        _c.Line("T value;");
        _c.Line("std::memcpy(&value, &slot, sizeof(T));");
        _c.Line("return value;");
        _c.Close();
        _c.Line();
        foreach (Thunk th in _b.Thunks)
            WriteThunk(th);
        WriteTable();
        _c.Close("}");
        _c.Line();
        WriteRegister(moduleKind);
    }

    void WriteLayoutChecks()
    {
        foreach (TypeModel t in Own)
        {
            if (t.Kind == TypeKind.Struct)
            {
                (int size, int align) = _b.Map.Layout(t);
                _c.Line($"static_assert(sizeof({Q(t)}) == {size} && alignof({Q(t)}) == {align}, \"{t.Name}: the layout C# was given\");");
                foreach (FieldModel f in t.Fields.Where(f => !f.Static))
                    _c.Line($"static_assert(offsetof({Q(t)}, {f.Name}) == {_b.Map.FieldOffset(t, f)}, \"{t.Name}.{f.Name}: the offset C# was given\");");
            }
            else if (t.Kind == TypeKind.Enum)
            {
                (int size, _) = _b.Map.EnumSize(t);
                _c.Line($"static_assert(sizeof({Q(t)}) == {size}, \"{t.Name}: the size C# was given\");");
                foreach (EnumValueModel v in t.EnumValues)
                    _c.Line($"static_assert(static_cast<long long>({Q(t)}::{v.Name}) == {v.Value}ll, \"{t.Name}.{v.Name}: the value C# was given\");");
            }
        }
        _c.Line();
    }

    // Private serialized fields: their member pointers through explicit instantiation (which does not check access).
    void WritePrivateAccess()
    {
        var fields = Own.SelectMany(t => t.Fields.Where(f => f.Tag.Has("Private") && !f.Static).Select(f => (t, f))).ToList();
        var methods = Own.Where(_b.IsScriptClass).SelectMany(t => _b.ScriptMethods(t)).Where(x => !x.Method.Public).Distinct().ToList();
        if (fields.Count == 0 && methods.Count == 0)
            return;
        _c.Line("template <class Tag, typename Tag::Type Member>");
        _c.Open("struct HxAccess");
        _c.Line("friend typename Tag::Type HxMember(Tag) { return Member; }");
        _c.Close("};");
        foreach ((TypeModel t, FieldModel f) in fields)
        {
            int k = _privateTags.Count;
            _privateTags[f] = k;
            _c.Open($"struct HxTag{k}");
            _c.Line($"using Type = {Spell(f.Type, f.Where, f.Name)} ({Q(t)}::*);");
            _c.Line($"friend Type HxMember(HxTag{k});");
            _c.Close("};");
            _c.Line($"template struct HxAccess<HxTag{k}, &{Q(t)}::{f.Name}>;");
        }
        // Private methods of script classes: their member function pointers the same way.
        foreach ((MethodModel m, TypeModel owner) in methods)
        {
            int k = _privateMethods.Count;
            _privateMethods[m] = k;
            string args = m.Parameters.Count == 1 ? "bool" : "";
            _c.Open($"struct HxMTag{k}");
            _c.Line($"using Type = void ({Q(owner)}::*)({args}){(m.Const ? " const" : "")};");
            _c.Line($"friend Type HxMember(HxMTag{k});");
            _c.Close("};");
            _c.Line($"template struct HxAccess<HxMTag{k}, &{Q(owner)}::{m.Name}>;");
        }
        _c.Line();
    }

    readonly Dictionary<MethodModel, int> _privateMethods = new();

    // The script classes of the module: how they are made and copied, and their methods without arguments or with one
    // bool (the engine finds its messages among them).
    void WriteScriptClasses(Dictionary<TypeModel, string> ids)
    {
        foreach (TypeModel t in _b.Ordered().Where(_b.IsScriptClass))
        {
            string q = Q(t);
            string root = Q(_b.RootOf(t));
            string k = ids[t];
            List<(MethodModel Method, TypeModel Owner)> methods = _b.ScriptMethods(t);
            _c.Open();
            _c.Open($"static const NativeScriptMethod methods[] =");
            foreach ((MethodModel m, TypeModel owner) in methods)
            {
                string self = $"static_cast<{q}*>(static_cast<{root}*>(p))";
                string call = _privateMethods.TryGetValue(m, out int pk) ? $"({self}->*HxMember(HxMTag{pk}{{}}))" : $"{self}->{m.Name}";
                _c.Line(m.Parameters.Count == 0
                    ? $"NativeScriptMethod{{\"{m.Name}\", [](void* p) {{ {call}(); }}, nullptr}},"
                    : $"NativeScriptMethod{{\"{m.Name}\", nullptr, [](void* p, bool v) {{ {call}(v); }}}},");
            }
            if (methods.Count == 0)
                _c.Line("NativeScriptMethod{},");
            _c.Close("};");
            _c.Line("NativeScriptClass c;");
            _c.Line($"c.type = {k};");
            _c.Line($"c.module = \"{_b.Module.Name}\";");
            _c.Line($"c.nameSpace = \"{t.CsNamespace}\";");
            _c.Line($"c.name = \"{t.RegistryName}\";");
            _c.Line($"c.scriptBase = \"{_b.BaseChain(t).Skip(1).First(b => b.Tag.Has("ScriptBase")).RegistryName}\";");
            _c.Line($"c.size = u32(sizeof({q}));");
            _c.Line($"c.alignment = u32(alignof({q}));");
            _c.Line($"c.construct = [](void* m) -> void* {{ return static_cast<{root}*>(new (m) {q}()); }};");
            _c.Line($"c.clone = [](void* m, const void* o) -> void* {{ return static_cast<{root}*>(new (m) {q}(*static_cast<const {q}*>(static_cast<const {root}*>(o)))); }};");
            _c.Line($"c.methods = Span<const NativeScriptMethod>(methods, {methods.Count}u);");
            _c.Line($"c.executionOrder = {(int.TryParse(t.Tag.Get("Order"), out int order) ? order : 0)};");
            if (_transfers.Contains(t))
                _c.Line($"c.transfer = &HxTransfer_{t.Ident};");
            _c.Line("RegisterNativeScriptClass(c);");
            _c.Close();
        }
    }

    // ------------------------------------------------------------------------------------------- serialization

    // Script classes with serialized fields (theirs or their own module's script bases'), the module's HX_STRUCTs those
    // fields hold (by value, in arrays, inside each other), and the C++ types of their object references.
    readonly List<TypeModel> _transfers = new();
    readonly List<TypeModel> _serializedStructs = new();
    readonly Dictionary<string, (TypeModel Bound, bool IsHandle)> _references = new();

    // The script class and its bases of this module below the script base, the base first.
    List<TypeModel> OwnScriptChain(TypeModel t) =>
        _b.BaseChain(t).TakeWhile(c => !c.Tag.Has("ScriptBase") && !c.External).Reverse().ToList();

    void CollectSerialization()
    {
        foreach (TypeModel t in _b.Ordered().Where(_b.IsScriptClass))
        {
            foreach (FieldModel f in t.Fields.Where(Binding.IsSerialized))
                CollectFieldType(f.Type, f.Where, $"{t.Name}.{f.Name}");
            if (OwnScriptChain(t).Any(c => c.Fields.Any(Binding.IsSerialized)))
                _transfers.Add(t);
        }
    }

    void CollectFieldType(TypeRef type, Location where, string what)
    {
        if (_b.ValueHandle(type) is TypeModel handle)
        {
            _references.TryAdd(Handle(handle), (handle, true));
            return;
        }
        string last = type.Name.Split("::")[^1];
        if (last == "Array" && type.Arguments.Count == 1)
        {
            CollectFieldType(type.Arguments[0], where, what);
            return;
        }
        Mapping m = _b.Map.Map(type, where, what);
        switch (m.Kind)
        {
            case MapKind.Object when type.Pointers == 1 && !type.Reference:
                _references.TryAdd(Q(m.Bound!) + "*", (m.Bound!, false));
                break;
            case MapKind.Struct when type.Pointers == 0 && !type.Reference:
                if (!m.Bound!.External && !_serializedStructs.Contains(m.Bound))
                {
                    _serializedStructs.Add(m.Bound);
                    foreach (FieldModel f in m.Bound.Fields.Where(Binding.IsSerialized))
                        CollectFieldType(f.Type, f.Where, $"{m.Bound.Name}.{f.Name}");
                }
                break;
            case MapKind.Primitive or MapKind.Bool or MapKind.Enum:
                break;
            case MapKind.String when !type.Name.EndsWith("StringView", StringComparison.Ordinal):
                break;
            default:
                throw new BindgenException(where, $"{what}: a {type.Spelling()} field is not serialized (mark it NonSerialized)");
        }
    }

    // The object references (EntityId values, checked against the field's type when read) and the structs' fields.
    void WriteSerializationTraits()
    {
        _c.Open("namespace helix::serialization");
        foreach ((string spelling, (TypeModel bound, bool isHandle)) in _references)
        {
            string root = Q(_b.RootOf(bound));
            string type = isHandle ? $"{spelling}::HxType()" : $"::helix::scripting::TypeOf<{Q(bound)}>()";
            _c.Line("template <>");
            _c.Open($"struct ObjectReferenceTraits<{spelling}>");
            _c.Line($"using T = {spelling};");
            _c.Line(isHandle
                ? "static ::helix::u64 Id(const T& o) { return o.HxId(); }"
                : $"static ::helix::u64 Id(const T& o) {{ return o ? ::helix::scripting::ObjectHandles<{root}>::ToId(o) : 0; }}");
            _c.Open("static void Set(T& o, ::helix::u64 id)");
            _c.Line($"{root}* r = id ? ::helix::scripting::ObjectHandles<{root}>::FromId(id) : nullptr;");
            _c.Line($"bool fits = r && ::helix::scripting::IsAssignableFrom({type}, ::helix::scripting::ObjectHandles<{root}>::TypeOf(r));");
            _c.Line(isHandle ? "o = T::HxFromId(fits ? id : 0);" : $"o = fits ? static_cast<{Q(bound)}*>(r) : nullptr;");
            _c.Close();
            _c.Close("};");
        }
        foreach (TypeModel s in _serializedStructs)
        {
            _c.Line("template <>");
            _c.Open($"struct TransferTraits<{Q(s)}>");
            _c.Line($"static constexpr ::helix::StringView kTypeName = \"{s.Name}\";");
            _c.Line("template <class V>");
            _c.Open($"static void Transfer(V& v, {Q(s)}& value)");
            foreach (FieldModel f in s.Fields.Where(Binding.IsSerialized))
                _c.Line($"v.Field(\"{f.CsName}\", {Access(s, f, "(&value)")});");
            _c.Close();
            _c.Close("};");
        }
        _c.Close("}");
        _c.Line();
    }

    // Each script class's serialized fields through the dynamic visitor: its module's script bases' first.
    void WriteScriptTransfers()
    {
        foreach (TypeModel t in _transfers)
        {
            string q = Q(t);
            _c.Open($"void HxTransfer_{t.Ident}(void* instance, void* visitor)");
            _c.Line($"{q}* self = static_cast<{q}*>(static_cast<{Q(_b.RootOf(t))}*>(instance));");
            _c.Open("::helix::serialization::VisitDynamic(*static_cast<::helix::serialization::DynamicVisitor*>(visitor), [self](auto& f)");
            foreach (TypeModel c in OwnScriptChain(t))
                foreach (FieldModel f in c.Fields.Where(Binding.IsSerialized))
                    _c.Line($"f.Field(\"{f.CsName}\", {Access(c, f, "self")});");
            _c.Close("});");
            _c.Close();
            _c.Line();
        }
    }

    string MemberPointer(TypeModel t, FieldModel f) => _privateTags.TryGetValue(f, out int k) ? $"HxMember(HxTag{k}{{}})" : $"&{Q(t)}::{f.Name}";

    string Access(TypeModel t, FieldModel f, string self) =>
        f.Static ? $"{Q(t)}::{f.Name}"
        : _privateTags.TryGetValue(f, out int k) ? $"({self}->*HxMember(HxTag{k}{{}}))"
        : $"{self}->{f.Name}";

    // ------------------------------------------------------------------------------------------- the bridge

    string Derived(TypeModel t) => $"HxDerived_{t.Ident}";

    // C++ values handed to a C# function: the C ABI types and the expressions (the C# side reads them as the
    // generated exports do).
    (List<string> Abi, List<string> Args, List<string> Prep) ToManaged(List<(TypeRef Type, string Name)> values, Location where, string what)
    {
        var abi = new List<string>();
        var args = new List<string>();
        var prep = new List<string>();
        foreach ((TypeRef a, string n) in values)
        {
            Mapping m = _b.Map.Map(a, where, what);
            bool isPointer = a.Pointers > 0;
            switch (m.Kind)
            {
                case MapKind.Primitive or MapKind.Enum:
                    abi.Add(CType(m));
                    args.Add(isPointer ? $"*{n}" : n);
                    break;
                case MapKind.Bool:
                    abi.Add("u8");
                    args.Add($"u8({n} ? 1 : 0)");
                    break;
                case MapKind.TypeId:
                    abi.Add("u32");
                    args.Add($"{n}.value");
                    break;
                case MapKind.Struct:
                    abi.Add($"const {CType(m)}*");
                    args.Add(isPointer ? n : $"&{n}");
                    break;
                case MapKind.String:
                    abi.Add("const char*");
                    abi.Add("i32");
                    prep.Add($"StringView {n}_v = {n};");
                    args.Add($"{n}_v.Data()");
                    args.Add($"i32({n}_v.Size())");
                    break;
                case MapKind.Object:
                    abi.Add("u64");
                    abi.Add("u32");
                    prep.Add($"InteropObject {n}_o = PassObject<{RootName(m)}>({(isPointer ? n : "&" + n)});");
                    args.Add($"{n}_o.id");
                    args.Add($"{n}_o.type");
                    break;
                case MapKind.Array:
                {
                    Mapping el = m.Element!;
                    if (el.Kind == MapKind.String)
                        throw new BindgenException(new Location(), "arrays of strings do not go to C# callbacks or events");
                    abi.Add(el.Kind == MapKind.Object ? "const InteropObject*" : $"const {CType(el)}*");
                    abi.Add("i32");
                    if (el.Kind == MapKind.Object)
                    {
                        prep.Add($"Array<InteropObject> {n}_ids;");
                        prep.Add($"for (auto* o : {n})");
                        prep.Add($"    {n}_ids.Push(PassObject<{RootName(el)}>(o));");
                        args.Add($"{n}_ids.Data()");
                        args.Add($"i32({n}_ids.Size())");
                    }
                    else
                    {
                        args.Add($"{n}.Data()");
                        args.Add($"i32({n}.Size())");
                    }
                    break;
                }
                default:
                    throw new BindgenException(where, $"{what}: {m.Cs} does not go to C#");
            }
        }
        return (abi, args, prep);
    }

    // The C type a C# function's result is written to, and the C++ value made of it.
    (string Decl, string Abi, string Value) FromManaged(TypeRef r, Location where, string what)
    {
        Mapping m = _b.Map.Map(r, where, what);
        return m.Kind switch
        {
            MapKind.Void => ("", "", ""),
            MapKind.Bool => ("u8 r = 0;", "u8*", "r != 0"),
            MapKind.TypeId => ("u32 r = 0;", "u32*", "TypeId{r}"),
            MapKind.Primitive or MapKind.Enum or MapKind.Struct when r.Pointers == 0 && !r.Reference => ($"{CType(m)} r{{}};", $"{CType(m)}*", "r"),
            MapKind.String when !r.Name.EndsWith("StringView", StringComparison.Ordinal) && !r.Reference =>
                ("InteropString16 r{};", "InteropString16*", "StringFromUtf16(r.data, r.size)"),
            MapKind.Object when r.Pointers == 1 && !r.Reference => ("InteropObject r{};", "InteropObject*", $"ObjectFromId<{RootName(m)}, {Q(m.Bound!)}>(r.id)"),
            _ => throw new BindgenException(where, $"{what}: a C# override or implementation answers {r.Spelling()}, which Bindgen does not bring back " +
                                                   "(values, String, objects by pointer)"),
        };
    }

    // The body of a C++ function that calls a C# function of the managed table with a GC handle; `fallback` is what
    // it does when C# is not there or failed.
    void ManagedCall(MethodModel m, string handle, int index, string what, string fallback)
    {
        var values = m.Parameters.Select((p, i) => (p.Type, $"a{i}")).ToList();
        (List<string> abi, List<string> args, List<string> prep) = ToManaged(values, m.Where, what);
        (string decl, string resultAbi, string value) = FromManaged(m.Return, m.Where, what);
        _c.Open("if (!gHxManaged)");
        _c.Line($"ReportBindingFailure(\"{what}\", InteropNotLoaded);");
        _c.Line(fallback);
        _c.Close();
        foreach (string l in prep)
            _c.Line(l);
        if (decl.Length > 0)
        {
            _c.Line(decl);
            abi.Add(resultAbi);
            args.Add("&r");
        }
        _c.Line($"i32 status = HxManagedFn<i32 (*)(u64{string.Join("", abi.Select(x => ", " + x))})>({index})({handle}{string.Join("", args.Select(x => ", " + x))});");
        _c.Open("if (status != 0)");
        _c.Line($"ReportBindingFailure(\"{what}\", status);");
        _c.Line(fallback);
        _c.Close();
        if (decl.Length > 0)
            _c.Line($"return {value};");
    }

    string Signature(MethodModel m, string name) =>
        $"{Spell(m.Return, m.Where, m.Name)} {name}({string.Join(", ", m.Parameters.Select((p, i) => $"{Spell(p.Type, m.Where, p.Name)} a{i}"))}){(m.Const ? " const" : "")}";

    string ArgList(MethodModel m) => string.Join(", ", m.Parameters.Select((_, i) => $"a{i}"));

    // The managed table, the adapters of interfaces and their casts, the C++ subclasses of classes C# derives from.
    void WriteBridge()
    {
        _c.Line("void* const* gHxManaged = nullptr;");
        _c.Line();
        _c.Line("template <class F>");
        _c.Line("[[maybe_unused]] F HxManagedFn(u32 index) { return std::bit_cast<F>(gHxManaged[index]); }");
        _c.Line();
        _c.Line("template <class T>");
        _c.Line("[[maybe_unused]] T HxDefault() { return T(); }");
        _c.Line();
        _c.Line("// A type of the module: the one it has (declared by the module's own registry), else a new one.");
        _c.Open("TypeId HxDeclare(ModuleId module, StringView nameSpace, StringView name, TypeKind kind, TypeId base, u32 flags)");
        _c.Line("String full(nameSpace);");
        _c.Line("full.Append(\".\");");
        _c.Line("full.Append(name);");
        _c.Line("TypeId known = FindType(full);");
        _c.Line("if (known.IsValid() && GetType(known)->module == module)");
        _c.Line("    return known;");
        _c.Line("return DeclareType(module, nameSpace, name, kind, base, flags);");
        _c.Close();
        _c.Line();
        foreach (TypeModel i in Own.Where(t => t.Kind == TypeKind.Interface))
        {
            string q = Q(i);
            _c.Line($"// {i.Name} implemented by a C# object: its calls go to the C# object of the handle.");
            _c.Open($"class HxAdapter_{i.Ident} final : public {q}");
            _c.Line("public:", -1);
            _c.Line($"explicit HxAdapter_{i.Ident}(u64 handle) : handle_(handle) {{}}");
            foreach (ManagedEntry e in _b.Managed.Where(e => e.Kind == ExportKind.Interface && e.Owner == i))
            {
                MethodModel m = e.Method!;
                _c.Open(Signature(m, m.Name) + " override");
                ManagedCall(m, "handle_", e.Index, $"{i.Name}.{m.CsName}", $"return HxDefault<{Spell(m.Return.Bare(), m.Where, m.Name)}>();");
                _c.Close();
            }
            _c.Line();
            _c.Line("private:", -1);
            _c.Line("u64 handle_;");
            _c.Close("};");
            _c.Line();
            _c.Line($"// A native object as {i.Name}: through the class that implements it.");
            _c.Open($"{q}* HxCastTo_{i.Ident}(u64 id, u32 type)");
            foreach (TypeModel c in _b.ImplementersOf(i))
            {
                _c.Line($"if (IsAssignableFrom(TypeOf<{Q(c)}>(), TypeId{{type}}))");
                _c.Line($"    return static_cast<{q}*>(ObjectFromId<{Q(_b.RootOf(c))}, {Q(c)}>(id));");
            }
            _c.Line("(void)id;");
            _c.Line("(void)type;");
            _c.Line("return nullptr;");
            _c.Close();
            _c.Line();
            _c.Line($"// A Variant of an object (held by its root's address) as {i.Name}.");
            _c.Open($"{q}* HxInterfaceOf_{i.Ident}(const Variant& value)");
            TypeModel? root = _b.ImplementersOf(i).Select(c => _b.RootOf(c)).FirstOrDefault();
            if (root != null)
            {
                _c.Line($"auto* o = static_cast<{Q(root)}*>(value.AsObject());");
                _c.Line($"return o ? HxCastTo_{i.Ident}(ObjectHandles<{Q(root)}>::ToId(o), value.Type().value) : nullptr;");
            }
            else
            {
                _c.Line("(void)value;");
                _c.Line("return nullptr;");
            }
            _c.Close();
            _c.Line();
        }
        foreach ((TypeModel t, List<Overridable> virtuals) in _b.Overridables)
        {
            string q = Q(t);
            string root = Q(_b.RootOf(t));
            _c.Line($"// {t.Name} of a C# class: its virtual functions call the C# overrides the class has (hxMask).");
            _c.Open($"class {Derived(t)} final : public {q}");
            _c.Line("public:", -1);
            _c.Line($"using {q}::{t.Name};");
            _c.Line("u64 hxMask = 0;");
            foreach (Overridable o in virtuals)
            {
                MethodModel m = o.Nearest;
                string ret = Spell(m.Return, m.Where, m.Name);
                string baseCall = o.Pure ? $"return HxDefault<{Spell(m.Return.Bare(), m.Where, m.Name)}>();" : $"return {Q(o.NearestOwner)}::{m.Name}({ArgList(m)});";
                _c.Line();
                _c.Open(Signature(m, m.Name) + " override");
                _c.Line($"if (!(hxMask & (u64(1) << {o.Bit})))");
                _c.Line($"    {baseCall}");
                _c.Line($"u64 handle = ObjectHandles<{root}>::WrapperOf(const_cast<{Derived(t)}*>(this));");
                ManagedCall(m, "handle", o.Export.Index, $"{t.Name}.{m.CsName}", baseCall);
                _c.Close();
                _c.Open(Signature(m, "HxBase_" + m.Name));
                if (o.Pure)
                {
                    _c.Line($"ReportBindingFailure(\"{t.Name}.{m.CsName}: abstract in C++\", InteropMissingObject);");
                    _c.Line(baseCall);
                }
                else
                    _c.Line(baseCall);
                _c.Close();
                _ = ret;
            }
            _c.Close("};");
            _c.Line();
        }
    }

