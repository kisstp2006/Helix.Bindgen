using System.Globalization;
using Helix.Bindgen.Model;

namespace Helix.Bindgen.Generators;

/// <summary>
/// The C++ script API of a module (one header): per bound class a value handle in the class's C# namespace that holds
/// the object's id and calls the module's function table (the thunks C# calls), with the C# names: property members
/// (`transform.position = v;`), methods with overloads and defaults, statics, constructors as New, generic methods as
/// templates; script base classes (ScriptBase) as C++ classes deriving from the engine's class with the members of
/// their chain, which C++ scripts derive from; value types and enums as aliases of the C++ types.
/// </summary>
public sealed class ApiGenerator
{
    static readonly HashSet<string> HelixAliases = new() { "i8", "u8", "i16", "u16", "i32", "u32", "i64", "u64", "f32", "f64" };

    readonly Binding _b;
    readonly Code _c = new();
    readonly string _module;

    ApiGenerator(Binding b)
    {
        _b = b;
        _module = $"kModule_{b.Ident(b.Module.Name)}";
    }

    public static string Generate(Binding b, IEnumerable<string> includes)
    {
        var g = new ApiGenerator(b);
        g.Write(includes.ToList());
        return g._c.ToString();
    }

    // ----------------------------------------------------------------------------------------------- names

    static string Q(TypeModel t) => "::" + t.CppName;
    static string Ns(TypeModel t) => t.CsNamespace.Replace(".", "::");
    string ApiQ(TypeModel t) => "::" + (Ns(t).Length > 0 ? Ns(t) + "::" : "") + t.Name;

    bool IsApiClass(TypeModel t) => t.Kind == TypeKind.Class && !t.External && t.Outer == null && !t.Tag.Has("Internal");
    bool IsHandle(TypeModel t) => _b.IsObjectClass(t) && !t.Tag.Has("ScriptBase");
    bool IsScriptBase(TypeModel t) => _b.IsObjectClass(t) && t.Tag.Has("ScriptBase");

    // The handle an object of the class crosses as: its own, or the nearest base's for a script base.
    string HandleOf(TypeModel bound)
    {
        foreach (TypeModel c in _b.BaseChain(bound))
            if (IsHandle(c))
                return ApiQ(c);
        throw new BindgenException(bound.Where, $"{bound.Name}: no handle class in its chain");
    }

    string RootQ(TypeModel t) => Q(_b.RootOf(t));

    static string PrimitiveName(string name) =>
        HelixAliases.Contains(name) ? "::helix::" + name : name.StartsWith("std::", StringComparison.Ordinal) || name.StartsWith("helix::", StringComparison.Ordinal) ? "::" + name : name;

    // The C++ type of a thunk's value (as the thunks spell it).
    string CType(Mapping m) => m.Kind switch
    {
        MapKind.Bool => "bool",
        MapKind.Primitive => PrimitiveName(m.CppBare),
        MapKind.TypeId => "::helix::scripting::TypeId",
        _ => Q(m.Bound!),
    };

    // The API's type of a value: results and stored values.
    string ApiValue(Mapping m) => m.Kind switch
    {
        MapKind.Void => "void",
        MapKind.Bool => "bool",
        MapKind.Primitive => PrimitiveName(m.CppBare),
        MapKind.TypeId => "::helix::scripting::TypeId",
        MapKind.String => "::helix::String",
        MapKind.Object => HandleOf(m.Bound!),
        MapKind.Array => $"::helix::Array<{ApiValue(m.Element!)}>",
        MapKind.Struct or MapKind.Enum => Q(m.Bound!),
        _ => throw new NotSupportedException(m.Kind.ToString()),
    };

    // The API's type of a parameter.
    string ApiIn(Mapping m)
    {
        if (m.ByRef)
            return ApiValue(m) + "&";
        return m.Kind switch
        {
            MapKind.Struct => $"const {Q(m.Bound!)}&",
            MapKind.String => "::helix::StringView",
            MapKind.Object => $"const {HandleOf(m.Bound!)}&",
            MapKind.Array => $"::helix::Span<const {ApiValue(m.Element!)}>",
            _ => ApiValue(m),
        };
    }

    static bool Supported(Mapping m) => m.Kind is not (MapKind.Interface) && (m.Element == null || Supported(m.Element));

    // ----------------------------------------------------------------------------------------------- the file

    void Write(List<string> includes)
    {
        _c.Line("// Generated by Helix.Bindgen. Do not edit.");
        _c.Line($"// The C++ script API of {_b.Module.Name}: value handles over the module's function table.");
        _c.Line("#pragma once");
        _c.Line();
        _c.Line("#include <Helix/Scripting/Bindings/ScriptApi.h>");
        foreach (string inc in includes)
            _c.Line($"#include {inc}");
        _c.Line();
        _c.Line("#include <bit>");
        _c.Line("#include <cstddef>");
        _c.Line("#include <cstring>");
        _c.Line();
        _c.Open("namespace helix::scripting::hxapi");
        _c.Line($"inline constexpr char {_module}[] = \"{_b.Module.Name}\";");
        // Every module's API has the helper; the first header included defines it.
        _c.Line("#ifndef HELIX_HXAPI_SLOT");
        _c.Line("#define HELIX_HXAPI_SLOT");
        _c.Line("// A value in an 8 byte slot of a call with many arguments (its bytes from the first).");
        _c.Line("template <class T>");
        _c.Line("inline ::helix::u64 Slot(T value)");
        _c.Line("{");
        _c.Line("    ::helix::u64 slot = 0;");
        _c.Line("    std::memcpy(&slot, &value, sizeof(T));");
        _c.Line("    return slot;");
        _c.Line("}");
        _c.Line("#endif");
        _c.Close();
        _c.Line();

        List<TypeModel> ordered = _b.Ordered();
        List<TypeModel> classes = ordered.Where(IsApiClass).ToList();
        // Names first: aliases of the value types and enums, the classes declared.
        foreach (IGrouping<string, TypeModel> ns in ordered.Where(t => t.Outer == null && !t.Tag.Has("Internal") &&
                                                                      (t.Kind is TypeKind.Struct or TypeKind.Enum || IsApiClass(t)))
                                                         .GroupBy(Ns))
        {
            _c.Open(ns.Key.Length > 0 ? $"namespace {ns.Key}" : "namespace");
            foreach (TypeModel t in ns)
                _c.Line(t.Kind == TypeKind.Class ? $"class {t.Name};" : $"using {t.Name} = {Q(t)};");
            _c.Close();
            _c.Line();
        }
        foreach (TypeModel t in classes)
            WriteClass(t);
        foreach (TypeModel t in classes)
            WriteDefinitions(t);
    }

    // The members a class shows: its own thunks, and for a script base those of its whole chain (nearest first).
    List<Thunk> MembersOf(TypeModel t)
    {
        IEnumerable<TypeModel> owners = IsScriptBase(t) ? _b.BaseChain(t) : new[] { t };
        var list = new List<Thunk>();
        var seen = new HashSet<string>();
        foreach (TypeModel o in owners)
            foreach (Thunk th in _b.Thunks.Where(x => x.Owner == o))
            {
                if (th.Kind is not (ThunkKind.Method or ThunkKind.FieldGet or ThunkKind.FieldSet))
                    continue;
                // Classes bound by hand to C# are not in the C++ script API (C++ uses the class itself).
                if (th.Type.Kind == MapKind.Handle)
                    continue;
                if (!Usable(th))
                    continue;
                string key = Key(th);
                // A member of a nearer class hides the same one of a base (overrides).
                if (o != t && !seen.Add(key))
                    continue;
                seen.Add(key);
                list.Add(th);
            }
        return list;
    }

    string Key(Thunk th) => th.Property != null ? "p:" + th.Property.CsName + (th.IsSetter ? "=" : "") :
                            th.Field != null ? "f:" + th.Field.CsName + (th.Kind == ThunkKind.FieldSet ? "=" : "") :
                            "m:" + th.Method!.CsName + "(" + string.Join(",", th.Method.Parameters.Select(p => p.Type.Spelling())) + ")";

    bool Usable(Thunk th)
    {
        if (!Supported(th.Type))
            return false;
        if (th.Method != null)
            foreach (ParameterModel p in th.Method.Parameters)
                if (!Supported(_b.Map.Map(p.Type, th.Method.Where, p.Name)))
                    return false;
        return true;
    }

    // ----------------------------------------------------------------------------------------------- classes

    void WriteClass(TypeModel t)
    {
        string ns = Ns(t);
        _c.Open(ns.Length > 0 ? $"namespace {ns}" : "namespace");
        TypeModel? baseModel = _b.BaseOf(t);
        if (IsScriptBase(t))
        {
            _c.Line($"// The base of C++ scripts: the engine's {t.Name} with the members of the script API.");
            _c.Open($"class {t.Name} : public {Q(t)}");
            _c.Line("public:", -1);
            _c.Line($"{t.Name}() = default;");
            _c.Line($"{t.Name}(const {t.Name}& other) : {Q(t)}(other) {{}}");
            _c.Line($"{t.Name}& operator=(const {t.Name}&) = delete;");
            // The API's classes by the names a script writes (the engine's classes of the chain would be found first).
            foreach (TypeModel b in _b.BaseChain(t).Skip(1).Where(IsHandle))
                _c.Line($"using {b.Name} = {ApiQ(b)};");
        }
        else if (IsHandle(t))
        {
            bool root = _b.RootOf(t) == t;
            // The nearest handle of the chain: a script base class (GameBehaviour, ScriptableObject) is what scripts
            // derive from, not a handle, so a class below one is a handle of the handle above it.
            TypeModel? handleBase = root ? null : _b.BaseChain(t).Skip(1).FirstOrDefault(IsHandle);
            string baseName = handleBase == null ? "::helix::scripting::ScriptHandle" : ApiQ(handleBase);
            _c.Line($"// A handle of the engine's {t.Name}: its id, null once the object is gone.");
            _c.Open($"class {t.Name} : public {baseName}");
            _c.Line("public:", -1);
            _c.Line($"{t.Name}() = default;");
            _c.Line($"{t.Name}(std::nullptr_t) {{}}");
            _c.Line($"{t.Name}(const {t.Name}& other) : {baseName}(other) {{}}");
            _c.Open($"{t.Name}& operator=(const {t.Name}& other)");
            _c.Line($"{baseName}::operator=(other);");
            _c.Line("return *this;");
            _c.Close();
            _c.Open($"static {t.Name} HxFromId(::helix::u64 id)");
            _c.Line($"{t.Name} h;");
            _c.Line("h.id_ = id;");
            _c.Line("return h;");
            _c.Close();
            _c.Open("static ::helix::scripting::TypeId HxType()");
            _c.Line("static ::helix::scripting::TypeId cache;");
            _c.Line($"return ::helix::scripting::ApiType(\"{t.CsFullName}\", cache);");
            _c.Close();
            _c.Line($"static constexpr const char* HxApiName() {{ return \"{t.CsFullName}\"; }}");
            if (root)
            {
                _c.Line("// The reference's null semantics: a destroyed object is null.");
                _c.Line("explicit operator bool() const;");
                _c.Line("bool operator==(std::nullptr_t) const { return !static_cast<bool>(*this); }");
                _c.Open($"friend bool operator==(const {t.Name}& a, const {t.Name}& b)");
                _c.Line("bool aliveA = static_cast<bool>(a), aliveB = static_cast<bool>(b);");
                _c.Line("return aliveA && aliveB ? a.HxId() == b.HxId() : aliveA == aliveB;");
                _c.Close();
            }
        }
        else
        {
            _c.Line($"// The static members of {t.Name}.");
            _c.Open($"class {t.Name}");
            _c.Line("public:", -1);
            _c.Line($"{t.Name}() = delete;");
        }
        foreach (TypeModel n in _b.Module.Types.Where(x => x.Outer == t && x.Kind is TypeKind.Struct or TypeKind.Enum))
            _c.Line($"using {n.Name} = {Q(n)};");

        List<Thunk> members = MembersOf(t);
        foreach (IGrouping<string, Thunk> prop in members.Where(th => th.Property != null || th.Field != null).GroupBy(PropName))
            WriteProperty(t, prop.ToList());
        foreach (Thunk th in members.Where(th => th.Property == null && th.Field == null))
            WriteMethodDeclaration(t, th);
        foreach (Thunk add in EventsOf(t))
            WriteEventDeclaration(add);
        _c.Close("};");
        _c.Close();
        _c.Line();
    }

    static string PropName(Thunk th) => th.Property?.CsName ?? th.Field!.CsName;

    // A property member: an empty member read and written like the C# property (its type cannot be copied, so `auto`
    // does not take it); a static one is a static member of the same kind.
    void WriteProperty(TypeModel t, List<Thunk> pair)
    {
        Thunk get = pair.First(th => !th.IsSetter && th.Kind != ThunkKind.FieldSet);
        Thunk? set = pair.FirstOrDefault(th => th.IsSetter || th.Kind == ThunkKind.FieldSet);
        string name = PropName(get);
        string s = $"HxProperty_{name}";
        string type = ApiValue(get.Type);
        _c.Line();
        _c.Open($"struct {s}");
        _c.Line($"{s}() = default;");
        _c.Line($"{s}(const {s}&) = delete;");
        _c.Line($"operator {type}() const;");
        _c.Line($"{type} Get() const;");
        if (set != null)
        {
            Mapping vm = SetterValue(set);
            _c.Line($"{s}& operator=({ApiIn(vm)} hxValue);");
            _c.Line($"{s}& operator=(const {s}& other);");
        }
        else
            _c.Line($"{s}& operator=(const {s}&) = delete;");
        _c.Close("};");
        _c.Line(get.Static ? $"static inline {s} {name}{{}};" : $"HX_NO_UNIQUE_ADDRESS {s} {name};");
    }

    Mapping SetterValue(Thunk set)
    {
        if (set.Kind == ThunkKind.FieldSet)
            return Plain(set.Type);
        ParameterModel p = set.Method!.Parameters[0];
        return Plain(_b.Map.Map(p.Type, set.Method.Where, p.Name));
    }

    static Mapping Plain(Mapping m) => new() { Kind = m.Kind, Cs = m.Cs, CppBare = m.CppBare, Size = m.Size, Align = m.Align, Element = m.Element, Bound = m.Bound };

    // ----------------------------------------------------------------------------------------------- methods

    sealed class Generic
    {
        public string Parameter = "T";
        public TypeModel? Bound;
    }

    Generic? GenericOf(MethodModel m)
    {
        string? g = m.Tag.Get("Generic");
        if (g == null)
            return null;
        string[] parts = g.Split(':', 2, StringSplitOptions.TrimEntries);
        return new Generic { Parameter = parts[0], Bound = parts.Length > 1 ? _b.Map.Find(parts[1].Replace(".", "::")) : null };
    }

    bool IsT(Generic? g, Mapping m) => g?.Bound != null && m.Kind == MapKind.Object && m.Bound == g.Bound;

    string Ref(Generic g, TypeModel owner) => $"::helix::scripting::ApiRef<{g.Parameter}, {GenericRoot(g, owner)}>";

    // The root class of a generic's objects: its constraint's (the owner may be a static class).
    string GenericRoot(Generic g, TypeModel owner) => g.Bound != null && _b.IsObjectClass(g.Bound) ? RootQ(g.Bound) : RootQ(owner);

    bool IsConstructor(Thunk th) => th.Method != null && (th.Method.RealConstructor || th.Method.Tag.Has("Constructor"));

    // The signature pieces of a method: the API's parameters (generic T and its type id taken out).
    (string Ret, List<string> Params, List<string> NoDefaults) Signature(TypeModel t, Thunk th, Generic? g)
    {
        MethodModel m = th.Method!;
        var ps = new List<string>();
        var noDefaults = new List<string>();
        foreach (ParameterModel p in m.Parameters)
        {
            Mapping pm = _b.Map.Map(p.Type, m.Where, p.Name);
            if (g != null && pm.Kind == MapKind.TypeId)
                continue;
            string type = IsT(g, pm) && pm.ByRef ? Ref(g!, t) + "&" : ApiIn(pm);
            string decl = $"{type} {Param(t, p.Name)}";
            noDefaults.Add(decl);
            // An enum member is named by the enum's full name (the enum may be in another API namespace).
            string? def = p.Default;
            if (def != null && pm.Kind == MapKind.Enum && def.Contains("::"))
                def = $"{ApiIn(pm)}::{def.Split("::")[^1]}";
            ps.Add(def != null ? $"{decl} = {def}" : decl);
        }
        string ret;
        Mapping r = th.Type;
        if (IsConstructor(th))
            ret = HandleOf(t);
        else if (IsT(g, r))
            ret = Ref(g!, t);
        else if (g != null && r.Kind == MapKind.Array && IsT(g, r.Element!))
            ret = $"::helix::Array<{Ref(g, t)}>";
        else
            ret = ApiValue(r);
        return (ret, ps, noDefaults);
    }

    static string Id(string name) => name is "default" or "new" or "delete" or "class" or "template" or "operator" ? name + "_" : name;

    // A parameter's name, unless a member of the class (or a base) has it (the member would be hidden).
    string Param(TypeModel t, string name)
    {
        var members = new HashSet<string>();
        foreach (TypeModel c in _b.BaseChain(t))
            foreach (Thunk th in _b.Thunks.Where(x => x.Owner == c))
            {
                if (th.Property != null)
                    members.Add(th.Property.CsName);
                if (th.Field != null)
                    members.Add(th.Field.CsName);
                if (th.Method != null)
                    members.Add(th.Method.CsName);
            }
        return members.Contains(name) ? name + "Value" : Id(name);
    }

    void WriteMethodDeclaration(TypeModel t, Thunk th)
    {
        MethodModel m = th.Method!;
        Generic? g = GenericOf(m);
        (string ret, List<string> ps, _) = Signature(t, th, g);
        string name = IsConstructor(th) ? "New" : m.CsName;
        bool isStatic = th.Static || IsConstructor(th);
        string template = g != null ? $"template <class {g.Parameter}>\n{new string(' ', 8)}" : "";
        _c.Line($"{template}{(isStatic ? "static " : "")}{ret} {name}({string.Join(", ", ps)}){(isStatic ? "" : " const")};");
        if (g != null && m.Tag.Has("Lists") && th.Type.Kind == MapKind.Array && IsT(g, th.Type.Element!))
        {
            List<string> listParams = Signature(t, th, g).NoDefaults.Append($"::helix::Array<{Ref(g, t)}>& results").ToList();
            _c.Line($"template <class {g.Parameter}>");
            _c.Line($"{(isStatic ? "static " : "")}void {name}({string.Join(", ", listParams)}){(isStatic ? "" : " const")};");
        }
    }

    // ----------------------------------------------------------------------------------------------- events

    // The events a class shows (its own; a script base's of its chain), whose arguments the API takes.
    List<Thunk> EventsOf(TypeModel t)
    {
        IEnumerable<TypeModel> owners = IsScriptBase(t) ? _b.BaseChain(t) : new[] { t };
        var list = new List<Thunk>();
        foreach (TypeModel o in owners)
            foreach (Thunk add in _b.Thunks.Where(x => x.Owner == o && x.Kind == ThunkKind.EventAdd))
                if (add.Event!.Arguments.All(a => EventArgSupported(_b.Map.Map(a, add.Event.Where, add.Event.CsName))))
                    list.Add(add);
        return list;
    }

    static bool EventArgSupported(Mapping m) => !m.ByRef && m.Kind is MapKind.Primitive or MapKind.Enum or MapKind.Bool or MapKind.Struct or MapKind.String or MapKind.Object;

    // A handler's argument in the API (by value) and in the thunk's C ABI.
    string EventApiArg(Mapping m) => m.Kind switch
    {
        MapKind.String => "::helix::StringView",
        MapKind.Object => HandleOf(m.Bound!),
        _ => ApiValue(m),
    };

    List<string> EventAbi(Mapping m) => m.Kind switch
    {
        MapKind.Bool => new() { "::helix::u8" },
        MapKind.Struct => new() { $"const {CType(m)}*" },
        MapKind.String => new() { "const char*", "::helix::i32" },
        MapKind.Object => new() { "::helix::u64", "::helix::u32" },
        _ => new() { CType(m) },
    };

    string EventValue(Mapping m, string n) => m.Kind switch
    {
        MapKind.Bool => $"{n} != 0",
        MapKind.Struct => $"*{n}",
        MapKind.String => $"::helix::StringView({n}, ::helix::usize({n}_n))",
        MapKind.Object => $"{HandleOf(m.Bound!)}::HxFromId({n})",
        _ => n,
    };

    string HandlerType(EventModel e) =>
        $"::helix::scripting::Callback<{(e.Query ? "bool" : "void")}({string.Join(", ", e.Arguments.Select(a => EventApiArg(_b.Map.Map(a, e.Where, e.CsName))))})>";

    void WriteEventDeclaration(Thunk add)
    {
        EventModel e = add.Event!;
        string s = $"HxEvent_{e.CsName}";
        _c.Line();
        _c.Line($"// The event {e.CsName}: Add answers a token that Remove takes.");
        _c.Open($"struct {s}");
        _c.Line($"using Handler = {HandlerType(e)};");
        _c.Line($"{s}() = default;");
        _c.Line($"{s}(const {s}&) = delete;");
        _c.Line("::helix::u64 Add(Handler handler) const;");
        _c.Line("void Remove(::helix::u64 token) const;");
        _c.Close("};");
        _c.Line(e.Static ? $"static inline {s} {e.CsName}{{}};" : $"HX_NO_UNIQUE_ADDRESS {s} {e.CsName};");
    }

    void WriteEventDefinitions(TypeModel t, Thunk add)
    {
        EventModel e = add.Event!;
        Thunk remove = _b.Thunks.First(x => x.Event == e && x.Kind == ThunkKind.EventRemove);
        string q = ApiQ(t);
        string s = $"{q}::HxEvent_{e.CsName}";
        string owner = $"reinterpret_cast<const {q}*>(reinterpret_cast<const char*>(this) - ::helix::scripting::OffsetOf(&{q}::{e.CsName}))";
        string? self = add.Static ? null : SelfOf(t, owner);
        var abi = new List<string>();
        var values = new List<string>();
        for (int i = 0; i < e.Arguments.Count; i++)
        {
            Mapping m = _b.Map.Map(e.Arguments[i], e.Where, e.CsName);
            List<string> types = EventAbi(m);
            abi.Add($"{types[0]} a{i}");
            if (types.Count > 1)
                abi.Add(m.Kind == MapKind.Object ? types[1] : $"{types[1]} a{i}_n");
            values.Add(EventValue(m, $"a{i}"));
        }
        string entry = $"HxEntry_{t.Ident}_{e.CsName}";
        _c.Open($"struct {entry}");
        _c.Line("::helix::u32 id = 0;");
        _c.Line("void* handle = nullptr;");
        _c.Line($"{s}::Handler handler;");
        _c.Close("};");
        _c.Line();
        _c.Open($"inline auto {s}::Add(Handler handler) const -> ::helix::u64");
        _c.Line($"auto* entry = new {entry}{{0, nullptr, handler}};");
        string ret = e.Query ? "::helix::u8" : "void";
        string call = $"hxEntry->handler.function(hxEntry->handler.user{string.Join("", values.Select(v => ", " + v))})";
        _c.Line($"{ret} (*adapter)(void*{string.Join("", abi.Select(a => ", " + a))}) = [](void* user{string.Join("", abi.Select(a => ", " + a))}) {{");
        _c.Line($"    auto* hxEntry = static_cast<{entry}*>(user);");
        _c.Line(e.Query ? $"    return ::helix::u8({call} ? 1 : 0);" : $"    {call};");
        _c.Line("};");
        var addAbi = new List<string>();
        var addArgs = new List<string>();
        if (self != null)
        {
            addAbi.Add("::helix::u64");
            addArgs.Add(self);
        }
        addAbi.AddRange(new[] { "void*", "void*", "::helix::u32*", "void**" });
        addArgs.AddRange(new[] { "std::bit_cast<void*>(adapter)", "entry", "&entry->id", "&entry->handle" });
        _c.Line($"using HxFn = ::helix::i32 (*)({string.Join(", ", addAbi)});");
        _c.Line($"auto hxFn = std::bit_cast<HxFn>(::helix::scripting::ApiFunction<::helix::scripting::hxapi::{_module}>({add.Index}u));");
        _c.Open($"if (!::helix::scripting::ApiCheck(std::bit_cast<const void*>(hxFn), \"{t.Name}.{e.CsName}\") || !::helix::scripting::ApiStatus(hxFn({string.Join(", ", addArgs)}), \"{t.Name}.{e.CsName}\"))");
        _c.Line("delete entry;");
        _c.Line("return 0;");
        _c.Close();
        _c.Line("return ::helix::u64(reinterpret_cast<::helix::uptr>(entry));");
        _c.Close();
        _c.Line();
        _c.Open($"inline auto {s}::Remove(::helix::u64 token) const -> void");
        _c.Line("if (!token)");
        _c.Line("    return;");
        _c.Line($"auto* entry = reinterpret_cast<{entry}*>(::helix::uptr(token));");
        var remAbi = new List<string>();
        var remArgs = new List<string>();
        if (self != null)
        {
            remAbi.Add("::helix::u64");
            remArgs.Add(self);
        }
        remAbi.AddRange(new[] { "::helix::u32", "void*" });
        remArgs.AddRange(new[] { "entry->id", "entry->handle" });
        _c.Line($"using HxFn = ::helix::i32 (*)({string.Join(", ", remAbi)});");
        _c.Line($"auto hxFn = std::bit_cast<HxFn>(::helix::scripting::ApiFunction<::helix::scripting::hxapi::{_module}>({remove.Index}u));");
        _c.Line("if (hxFn)");
        _c.Line($"    ::helix::scripting::ApiStatus(hxFn({string.Join(", ", remArgs)}), \"{t.Name}.{e.CsName}\");");
        _c.Line("delete entry;");
        _c.Close();
        _c.Line();
    }

