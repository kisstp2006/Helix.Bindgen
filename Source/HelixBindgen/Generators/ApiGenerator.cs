    // The call: the function of the table, the arguments in the thunk's ABI, the status, the result.
    sealed class Call
    {
        public readonly List<string> Abi = new();
        public readonly List<string> Args = new();
        public readonly List<string> Prep = new();
        public readonly List<string> Post = new();
    }

    void In(Call call, Mapping m, string n, Generic? g, TypeModel owner)
    {
        if (m.ByRef)
        {
            if (m.Kind == MapKind.Object)
            {
                call.Abi.Add("::helix::scripting::InteropObject*");
                call.Prep.Add($"::helix::scripting::InteropObject {n}_o{{}};");
                call.Args.Add($"&{n}_o");
                call.Post.Add(IsT(g, m) ? $"{n} = ::helix::scripting::ApiAs<{g!.Parameter}, {GenericRoot(g, owner)}>({n}_o.id);"
                                        : $"{n} = {HandleOf(m.Bound!)}::HxFromId({n}_o.id);");
                return;
            }
            call.Abi.Add(CType(m) + "*");
            call.Args.Add($"&{n}");
            return;
        }
        switch (m.Kind)
        {
            case MapKind.Primitive:
            case MapKind.Enum:
                call.Abi.Add(CType(m));
                call.Args.Add(n);
                break;
            case MapKind.Bool:
                call.Abi.Add("::helix::u8");
                call.Args.Add($"::helix::u8({n} ? 1 : 0)");
                break;
            case MapKind.TypeId:
                call.Abi.Add("::helix::u32");
                call.Args.Add($"{n}.value");
                break;
            case MapKind.Struct:
                call.Abi.Add($"const {CType(m)}*");
                call.Args.Add($"&{n}");
                break;
            case MapKind.String:
                call.Abi.Add("const char16_t*");
                call.Abi.Add("::helix::i32");
                call.Prep.Add($"::helix::scripting::ApiString16 {n}_u({n});");
                call.Args.Add($"{n}_u.Data()");
                call.Args.Add($"{n}_u.Size()");
                break;
            case MapKind.Object:
                call.Abi.Add("::helix::u64");
                call.Args.Add($"{n}.HxId()");
                break;
            case MapKind.Array:
            {
                Mapping e = m.Element!;
                if (e.Kind == MapKind.String)
                {
                    call.Abi.Add("const ::helix::scripting::InteropString16*");
                    call.Abi.Add("::helix::i32");
                    call.Prep.Add($"::helix::Array<::helix::scripting::ApiString16> {n}_u;");
                    call.Prep.Add($"for (const auto& s : {n})");
                    call.Prep.Add($"    {n}_u.Push(::helix::scripting::ApiString16(s));");
                    call.Prep.Add($"::helix::Array<::helix::scripting::InteropString16> {n}_s;");
                    call.Prep.Add($"for (const auto& u : {n}_u)");
                    call.Prep.Add($"    {n}_s.Push(::helix::scripting::InteropString16{{u.Data(), u.Size()}});");
                    call.Args.Add($"{n}_s.Data()");
                    call.Args.Add($"::helix::i32({n}_s.Size())");
                }
                else if (e.Kind == MapKind.Object)
                {
                    call.Abi.Add("const ::helix::u64*");
                    call.Abi.Add("::helix::i32");
                    call.Prep.Add($"::helix::Array<::helix::u64> {n}_ids;");
                    call.Prep.Add($"for (const auto& e : {n})");
                    call.Prep.Add($"    {n}_ids.Push(e.HxId());");
                    call.Args.Add($"{n}_ids.Data()");
                    call.Args.Add($"::helix::i32({n}_ids.Size())");
                }
                else
                {
                    call.Abi.Add($"const {CType(e)}*");
                    call.Abi.Add("::helix::i32");
                    call.Args.Add($"{n}.Data()");
                    call.Args.Add($"::helix::i32({n}.Size())");
                }
                break;
            }
            default:
                throw new NotSupportedException(m.Kind.ToString());
        }
    }

    // The result: its declaration, ABI type and the API value made of it.
    (string Decl, string Abi, string Value) Result(Mapping r, Generic? g, TypeModel owner, bool constructor)
    {
        string As(string id) => constructor ? $"{HandleOf(owner)}::HxFromId({id})"
                                : IsT(g, r) ? $"::helix::scripting::ApiAs<{g!.Parameter}, {GenericRoot(g!, owner)}>({id})"
                                : $"{HandleOf(r.Bound!)}::HxFromId({id})";
        switch (r.Kind)
        {
            case MapKind.Void:
                return ("", "", "");
            case MapKind.Bool:
                return ("::helix::u8 hxR = 0;", "::helix::u8*", "hxR != 0");
            case MapKind.TypeId:
                return ("::helix::u32 hxR = 0;", "::helix::u32*", "::helix::scripting::TypeId{hxR}");
            case MapKind.String:
                return ("::helix::scripting::InteropString hxR{};", "::helix::scripting::InteropString*", "::helix::scripting::ApiString(hxR)");
            case MapKind.Object:
                return ("::helix::scripting::InteropObject hxR{};", "::helix::scripting::InteropObject*", As("hxR.id"));
            case MapKind.Array:
            {
                Mapping e = r.Element!;
                string el = IsT(g, e) ? Ref(g!, owner) : ApiValue(e);
                string item = e.Kind == MapKind.Object
                    ? (IsT(g, e) ? $"::helix::scripting::ApiAs<{g!.Parameter}, {GenericRoot(g!, owner)}>(p[i].id)" : $"{HandleOf(e.Bound!)}::HxFromId(p[i].id)")
                    : e.Kind == MapKind.String ? "::helix::scripting::ApiString(p[i])" : "p[i]";
                string pt = e.Kind == MapKind.Object ? "::helix::scripting::InteropObject" : e.Kind == MapKind.String ? "::helix::scripting::InteropString" : CType(e);
                return ("::helix::scripting::InteropArray hxR{};", "::helix::scripting::InteropArray*",
                        $"[&] {{ ::helix::Array<{el}> v; const auto* p = static_cast<const {pt}*>(hxR.data); " +
                        $"for (::helix::i32 i = 0; i < hxR.count; i++) v.Push({item}); return v; }}()");
            }
            default:
                return ($"{CType(r)} hxR{{}};", $"{CType(r)}*", "hxR");
        }
    }

    // The owner's id: the handle's, or for a script base the object itself.
    string SelfOf(TypeModel t, string owner) => IsScriptBase(t)
        ? $"::helix::scripting::ObjectHandles<{RootQ(t)}>::ToId(static_cast<const {RootQ(t)}*>({owner}))"
        : $"{owner}->HxId()";

    // A body calling the thunk; `self` is the owner's id expression (null for statics), `done` what a property
    // setter returns.
    void Body(Thunk th, List<(Mapping M, string Name)> args, string? self, Generic? g, TypeModel owner, string what, string? returns,
              string? typeArg, string apiReturn)
    {
        var call = new Call();
        if (self != null)
        {
            call.Abi.Add("::helix::u64");
            call.Args.Add(self);
        }
        if (typeArg != null)
        {
            call.Abi.Add("::helix::u32");
            call.Args.Add(typeArg);
        }
        foreach ((Mapping m, string n) in args)
            In(call, m, n, g, owner);
        bool constructor = IsConstructor(th);
        // A field's setter answers nothing (its Type is the field's).
        Mapping resultType = constructor ? new Mapping { Kind = MapKind.Object, Bound = owner }
                             : th.Kind == ThunkKind.FieldSet ? new Mapping { Kind = MapKind.Void } : th.Type;
        (string decl, string abi, string value) = Result(resultType, g, owner, constructor);
        if (decl.Length > 0)
        {
            call.Abi.Add(abi);
            call.Args.Add("&hxR");
        }
        string fail = returns != null ? $"return {returns};" : apiReturn == "void" ? "return;" : $"return {apiReturn}();";
        bool packed = call.Abi.Count > Shared.MaxThunkParameters;
        _c.Line($"using HxFn = ::helix::i32 (*)({(packed ? "const ::helix::u64*" : string.Join(", ", call.Abi))});");
        _c.Line($"auto hxFn = std::bit_cast<HxFn>(::helix::scripting::ApiFunction<::helix::scripting::hxapi::{_module}>({th.Index}u));");
        _c.Line($"if (!::helix::scripting::ApiCheck(std::bit_cast<const void*>(hxFn), \"{what}\"))");
        _c.Line($"    {fail}");
        foreach (string l in call.Prep)
            _c.Line(l);
        if (decl.Length > 0)
            _c.Line(decl);
        string callArgs = string.Join(", ", call.Args);
        if (packed)
        {
            // Many arguments go as one array of 8 byte slots (see Shared.MaxThunkParameters).
            _c.Line($"const ::helix::u64 hxA[] = {{{string.Join(", ", call.Abi.Select((a, i) => $"::helix::scripting::hxapi::Slot<{a}>({call.Args[i]})"))}}};");
            callArgs = "hxA";
        }
        _c.Line($"if (!::helix::scripting::ApiStatus(hxFn({callArgs}), \"{what}\"))");
        _c.Line($"    {fail}");
        foreach (string l in call.Post)
            _c.Line(l);
        if (returns != null)
            _c.Line($"return {returns};");
        else if (decl.Length > 0)
            _c.Line($"return {value};");
    }

    void WriteDefinitions(TypeModel t)
    {
        string q = ApiQ(t);
        if (IsHandle(t) && _b.RootOf(t) == t)
        {
            Thunk alive = _b.Thunks.First(x => x.Owner == t && x.Kind == ThunkKind.Alive);
            _c.Open($"inline {q}::operator bool() const");
            _c.Line("if (!id_)");
            _c.Line("    return false;");
            _c.Line("using HxFn = ::helix::i32 (*)(::helix::u64, ::helix::u8*);");
            _c.Line($"auto hxFn = std::bit_cast<HxFn>(::helix::scripting::ApiFunction<::helix::scripting::hxapi::{_module}>({alive.Index}u));");
            _c.Line("::helix::u8 alive = 0;");
            _c.Line("return hxFn && hxFn(id_, &alive) == 0 && alive != 0;");
            _c.Close();
            _c.Line();
        }
        List<Thunk> members = MembersOf(t);
        foreach (Thunk add in EventsOf(t))
            WriteEventDefinitions(t, add);
        foreach (IGrouping<string, Thunk> prop in members.Where(th => th.Property != null || th.Field != null).GroupBy(PropName))
        {
            List<Thunk> pair = prop.ToList();
            Thunk get = pair.First(th => !th.IsSetter && th.Kind != ThunkKind.FieldSet);
            Thunk? set = pair.FirstOrDefault(th => th.IsSetter || th.Kind == ThunkKind.FieldSet);
            string name = PropName(get);
            string s = $"{q}::HxProperty_{name}";
            string owner = $"reinterpret_cast<const {q}*>(reinterpret_cast<const char*>(this) - ::helix::scripting::OffsetOf(&{q}::{name}))";
            string? self = get.Static ? null : SelfOf(t, owner);
            _c.Line($"inline {s}::operator {ApiValue(get.Type)}() const {{ return Get(); }}");
            if (set != null)
                _c.Line($"inline auto {s}::operator=(const HxProperty_{name}& other) -> HxProperty_{name}& {{ return *this = other.Get(); }}");
            _c.Open($"inline auto {s}::Get() const -> {ApiValue(get.Type)}");
            Body(get, new(), self, null, t, $"{t.Name}.{name}", null, null, ApiValue(get.Type));
            _c.Close();
            _c.Line();
            if (set != null)
            {
                Mapping vm = SetterValue(set);
                _c.Open($"inline auto {s}::operator=({ApiIn(vm)} hxValue) -> HxProperty_{name}&");
                Body(set, new() { (vm, "hxValue") }, self, null, t, $"{t.Name}.{name}", "*this", null, "");
                _c.Close();
                _c.Line();
            }
        }
        foreach (Thunk th in members.Where(th => th.Property == null && th.Field == null))
        {
            MethodModel m = th.Method!;
            Generic? g = GenericOf(m);
            (string ret, _, List<string> noDefaults) = Signature(t, th, g);
            bool isStatic = th.Static || IsConstructor(th);
            string name = IsConstructor(th) ? "New" : m.CsName;
            var args = new List<(Mapping, string)>();
            string? typeArg = null;
            foreach (ParameterModel p in m.Parameters)
            {
                Mapping pm = _b.Map.Map(p.Type, m.Where, p.Name);
                if (g != null && pm.Kind == MapKind.TypeId)
                {
                    // The generic's type id goes where the C++ function takes it.
                    args.Add((pm, $"::helix::scripting::ApiTypeOf<{g.Parameter}>()"));
                    continue;
                }
                args.Add((pm, Param(t, p.Name)));
            }
            string self = isStatic ? null! : SelfOf(t, "this");
            if (g != null)
                _c.Line($"template <class {g.Parameter}>");
            _c.Open($"inline auto {q}::{name}({string.Join(", ", noDefaults)}){(isStatic ? "" : " const")} -> {ret}");
            Body(th, args, isStatic ? null : self, g, t, $"{t.Name}.{m.CsName}", null, typeArg, ret);
            _c.Close();
            _c.Line();
            if (g != null && m.Tag.Has("Lists") && th.Type.Kind == MapKind.Array && IsT(g, th.Type.Element!))
            {
                _c.Line($"template <class {g.Parameter}>");
                string call = $"{name}<{g.Parameter}>({string.Join(", ", args.Where(a => a.Item1.Kind != MapKind.TypeId).Select(a => a.Item2))})";
                _c.Open($"inline void {q}::{name}({string.Join(", ", noDefaults.Append($"::helix::Array<{Ref(g, t)}>& results"))}){(isStatic ? "" : " const")}");
                _c.Line($"results = {call};");
                _c.Close();
                _c.Line();
            }
        }
    }
